N_RECIPES = 155


@functools.cache
def build():
    R = rng("long_19_recipe_nutrition")
    plan = (DISHES * 5)[:N_RECIPES]
    R.shuffle(plan)
    recipes, titles = [], set()
    for fn in plan:
        for _attempt in range(30):
            c = Ctx(R, "", "")
            fn(c)
            if c.title not in titles:
                break
        else:
            c.title += " (второй вариант)"
        titles.add(c.title)
        recipes.append(c)
    recipes.sort(key=lambda c: SECTION_ORDER.index(c.section))
    for i, c in enumerate(recipes, 1):
        c.rid = f"r{i:03d}"
        c.style = R.choice("ABC")
    errata = make_errata(R, recipes)
    files = {"cookbook/preface.md": PREFACE,
             "cookbook/errata.md": render_errata(R, errata),
             "reference/measures.md": render_measures(),
             "reference/nutrition.csv": render_nutrition_csv()}
    for c in recipes:
        files[f"cookbook/recipes/{c.rid}.md"] = render_recipe(c)
    truth = {c.rid: c.totals() for c in recipes}
    return {"recipes": recipes, "files": files, "truth": truth}


