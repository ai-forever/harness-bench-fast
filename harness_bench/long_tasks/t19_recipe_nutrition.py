class Ing:
    def __init__(self, key, unit, q, *, size=None, cat=None, role="list", big=False, words=False, group=""):
        self.key, self.unit, self.q = key, unit, Fraction(q)
        self.size, self.cat, self.role = size, cat, role
        self.big = big  # glass stated explicitly as 250 ml
        self.words = words
        self.group = group
        self.printed_q = None  # quantity as printed when an erratum corrects it
        self.parts_g = 0.0  # numeric part amounts mentioned in the steps (not additions)
        self.in_list = True

    @property
    def counted(self):
        return self.role in COUNTED

    def grams(self, q=None, glass250=False) -> float:
        q = self.q if q is None else Fraction(q)
        meas = USED[self.key][3]
        u = self.unit
        if u == "g":
            return float(q)
        if u == "ml":
            return float(q) * meas["ml"]
        if u == "glass":
            g200, g250 = meas["glass"]
            return float(q) * (g250 if (self.big or glass250) else g200)
        if u == "pcs":
            if self.key == "egg":
                return float(q) * EGG_G[self.cat or "С1"]
            if "pcs1" in meas:
                return float(q) * meas["pcs1"]
            return float(q) * meas["pcs"][SIZE_IDX[self.size or "средн"]]
        return float(q) * meas[u]

    # ---- rendering --------------------------------------------------------
    def measure_text(self, q=None) -> str:
        """Quantity for «Продукт — количество» lines."""
        q = self.q if q is None else Fraction(q)
        u = self.unit
        if u == "g":
            return f"{fmt_dec(q)} г"
        if u == "ml":
            if q >= 500 and q % 250 == 0:
                return f"{fmt_dec(q / 1000)} л"
            return f"{fmt_dec(q)} мл"
        if u == "glass":
            forms = GLASS_WORDS[q]
            t = forms[0] if self.words else forms[-1] if len(forms) > 1 else forms[0]
            return t + (" (стакан 250 мл)" if self.big else "")
        if u in ("tbsp", "tsp"):
            return spoon_text(q, u, self.words)
        if u == "pcs":
            n = int(q)
            t = f"{n} шт."
            if self.key == "egg" and self.cat:
                t += f", категория {self.cat}"
            if self.size:
                t += f" {SIZE_GEN[self.size]}"
            return t
        if u == "bunch":
            return {Fraction(1, 2): "½ пучка", Fraction(1): "1 пучок", Fraction(2): "2 пучка"}[q]
        if u == "pinch":
            return "щепотка" if q == 1 else f"{int(q)} щепотки"
        if u == "knife":
            return "на кончике ножа"
        if u == "handful":
            return "горсть" if q == 1 else f"{int(q)} горсти"
        if u == "pack":
            return "1 пакетик" if q == 1 else f"{int(q)} пакетика"
        if u == "clove":
            n = int(q)
            return f"{n} {('зубчик', 'зубчика', 'зубчиков')[plural_idx(n)]}"
        raise ValueError(u)

    def phrase(self, q=None) -> str:
        """Quantity + product in genitive: «1½ стакана пшеничной муки», «2 средние луковицы»."""
        q = self.q if q is None else Fraction(q)
        gen = USED[self.key][2]
        u = self.unit
        if u == "pcs":
            n = int(q)
            forms, g = PIECES[self.key]
            i = plural_idx(n)
            num_t = NUM_WORDS[g][n] if (self.words and n in NUM_WORDS[g]) else str(n)
            if self.key == "egg":
                t = f"{num_t} {forms[i]}" + (f" {self.cat}" if self.cat else "")
            elif self.size:
                t = f"{num_t} {SIZE_ADJ[g][self.size][i]} {forms[i]}"
            else:
                t = f"{num_t} {forms[i]}"
            return t
        if u == "knife":
            return f"{gen} на кончике ножа"
        if u == "bunch":
            return {Fraction(1, 2): "полпучка", Fraction(1): "пучок", Fraction(2): "2 пучка"}[q] + f" {gen}"
        if u == "clove":
            return f"{self.measure_text(q)} {gen}"
        return f"{self.measure_text(q)} {gen}"


class Ctx:
    """Collects one recipe while a dish function describes it."""

    def __init__(self, R, rid, section):
        self.R, self.rid, self.section = R, rid, section
        self.ings: list[Ing] = []
        self.steps: list[str] = []
        self.tips: list[str] = []
        self.intro: list[str] = []
        self.servings = 0
        self.yield_kind = None
        self.yield_args = None
        self.printed_servings = None
        self.title = ""
        self.style = "A"
        self.groups_order: list[str] = []

    # helpers ---------------------------------------------------------------
    def step(self, text):
        self.steps.append(text)

    def pick(self, seq):
        return self.R.choice(list(seq))

    def chance(self, p):
        return self.R.random() < p

    def _make(self, key, opts, role, size=None, cat=None, group=""):
        unit, vals = self.R.choice(opts)
        q = Fraction(self.R.choice(vals)).limit_denominator(12)
        big = unit == "glass" and role == "list" and self.R.random() < 0.14
        words = self.R.random() < 0.35 and role != "per_serv"
        if size == "?":
            size = self.R.choice(["мелк", "средн", "средн", "крупн", None])
        if cat == "?":
            cat = self.R.choice(["С0", "С1", "С2", None, None])
        ing = Ing(key, unit, q, size=size, cat=cat, role=role, big=big, words=words, group=group)
        self.ings.append(ing)
        if group and group not in self.groups_order:
            self.groups_order.append(group)
        return ing

    def ing(self, key, *opts, size=None, cat=None, group=""):
        return self._make(key, opts, "list", size, cat, group)

    def opt(self, key, *opts, group=""):
        return self._make(key, opts, "opt", group=group)

    def alt(self, key, *opts, size=None, group=""):
        return self._make(key, opts, "alt", size=size, group=group)

    def serv(self, key, *opts, in_list=True):
        ing = self._make(key, opts, "per_serv", group="Для подачи" if in_list else "")
        ing.in_list = in_list
        return ing

    def new(self, key, *opts, size=None, cat=None):
        return self._make(key, opts, "step_new", size, cat).phrase()

    def extra(self, key, *opts):
        return "ещё " + self._make(key, opts, "step_extra").phrase()

    def variant(self, key, *opts):
        return self._make(key, opts, "variant").phrase()

    def taste(self, *labels):
        self.ings.append(("taste", labels))

    def part(self, ing: Ing) -> tuple[str, str]:
        """Split a listed amount into a first portion and «the rest» for the steps."""
        gen = USED[ing.key][2]
        if ing.unit in ("g", "ml") and ing.q >= 100:
            first = Fraction(int(ing.q * Fraction(self.pick([3, 2]), 5) / 10) * 10)
            rest = ing.q - first
            tmp = Ing(ing.key, ing.unit, first)
            ing.parts_g += ing.grams(first) + ing.grams(rest)
            return tmp.phrase(), f"оставшиеся {tmp.measure_text(rest)} {gen}"
        if ing.unit == "glass" and ing.q in (Fraction(3, 2), Fraction(2), Fraction(5, 2), Fraction(3)):
            first = Fraction(1)
            rest = ing.q - first
            ing.parts_g += ing.grams(first) + ing.grams(rest)
            tmp = Ing(ing.key, "glass", first, words=True)
            if rest == 1:
                return tmp.phrase(), f"оставшийся стакан {gen}"
            return tmp.phrase(), f"оставшиеся {GLASS_WORDS[rest][0]} {gen}"
        return f"половину {gen}", f"оставшуюся часть {gen}"

    # yields ----------------------------------------------------------------
    def portions(self, *ns):
        self.servings = self.pick(ns)
        self.yield_kind = "portions"

    def portions_range(self, pairs):
        a, b = self.pick(pairs)
        self.servings = b
        self.yield_kind = "range"
        self.yield_args = a

    def pieces(self, forms, *ns):
        self.servings = self.pick(ns)
        self.yield_kind = "pieces"
        self.yield_args = forms

    def form(self, diam, *ns):
        self.servings = self.pick(ns)
        self.yield_kind = "form"
        self.yield_args = diam

    def weight(self, portion, *ns):
        self.servings = self.pick(ns)
        self.yield_kind = "weight"
        self.yield_args = portion

    def yield_text(self) -> str:
        n = self.printed_servings or self.servings
        R = self.R
        por = ("порцию", "порции", "порций")[plural_idx(n)]
        if self.yield_kind == "portions":
            return R.choice([f"на {n} {por}", f"порций: {n}", f"рецепт рассчитан на {n} {por}",
                             f"{n} {('порция', 'порции', 'порций')[plural_idx(n)]}"])
        if self.yield_kind == "range":
            return f"на {self.yield_args}–{n} {('порцию', 'порции', 'порций')[plural_idx(n)]}"
        if self.yield_kind == "pieces":
            forms = self.yield_args
            return R.choice([f"{n} {forms[plural_idx(n)]}", f"получается {n} {forms[plural_idx(n)]}"])
        if self.yield_kind == "form":
            return R.choice([f"форма диаметром {self.yield_args} см, пирог режут на {n} "
                             f"{('кусок', 'куска', 'кусков')[plural_idx(n)]}",
                             f"одна форма {self.yield_args} см — {n} "
                             f"{('кусок', 'куска', 'кусков')[plural_idx(n)]}"])
        if self.yield_kind == "weight":
            p = self.yield_args
            return f"около {fmt_dec(p * n)} г готового блюда, порция — {p} г"
        raise ValueError(self.yield_kind)

    # truth -------------------------------------------------------------------
    def totals(self, *, glass250=False, variants=False, steps=True, divide=True, errata=True,
               parts=False):
        tot = [0.0, 0.0, 0.0, 0.0]
        for ing in self.ings:
            if isinstance(ing, tuple):
                continue
            use = ing.counted or (variants and ing.role in ("opt", "alt", "variant"))
            if not steps and ing.role in ("step_new", "step_extra"):
                use = False
            q = ing.q if (errata or ing.printed_q is None) else ing.printed_q
            g = ing.grams(q, glass250=glass250) if use else 0.0
            if parts:
                g += ing.parts_g
            if ing.role == "per_serv" and use:
                n = self.servings if errata or not self.printed_servings else self.printed_servings
                g *= n
            nut = NUTR_BY_NAME[USED[ing.key][0]]
            for i in range(4):
                tot[i] += g * nut[i] / 100
        n = self.servings if (errata or not self.printed_servings) else self.printed_servings
        if divide:
            tot = [t / n for t in tot]
        return tuple(round(t, 1) for t in tot)


