def _cap(s: str) -> str:
    return s[:1].upper() + s[1:]


def _list_line(ing: Ing, style: str) -> str:
    q = ing.printed_q if ing.printed_q is not None else ing.q
    nom = USED[ing.key][1]
    if ing.key == "egg" and ing.unit == "pcs":
        nom = "яйца куриные" if style == "C" else "яйца"
    per = ing.role == "per_serv"
    if style == "B":
        body = ("по " if per else "") + ing.phrase(q)
        line = f"- {body}"
    elif style == "A":
        line = f"- {_cap(nom)} — {'по ' if per else ''}{ing.measure_text(q)}"
    else:
        line = f"- {nom}: {'по ' if per else ''}{ing.measure_text(q)}"
    if per:
        line += " на порцию"
    if ing.role == "opt":
        line += " (по желанию)"
    return line + ("" if style == "C" else "")


def _old_amount(c: Ctx):
    cands = [i for i in c.ings if not isinstance(i, tuple) and i.role == "list"
             and i.unit in ("g", "glass", "tbsp") and i.printed_q is None]
    if not cands:
        return None
    ing = c.pick(cands)
    if ing.unit == "glass":
        alts = [q for q in GLASS_WORDS if q != ing.q and abs(float(q - ing.q)) <= 1]
        if not alts:
            return None
        q = c.pick(alts)
    elif ing.unit == "g":
        q = ing.q + c.pick([50, 100]) if ing.q >= 100 else ing.q + 10
    else:
        q = ing.q + 1
    return ing.phrase(q)


def render_recipe(c: Ctx) -> str:
    R = c.R
    out = [f"# {c.title}", "", f"*Рецепт {c.rid} · раздел «{c.section}»*", ""]
    specific = list(c.intro)
    cat = R.sample(INTRO_CAT[c.section], k=min(len(INTRO_CAT[c.section]), R.randint(2, 3)))
    gen = R.sample(INTRO_GENERIC, k=R.randint(7, 10))
    body = specific[:1] + R.sample(specific[1:] + cat + gen, k=len(specific) - 1 + len(cat) + len(gen))
    if R.random() < 0.45:
        old = _old_amount(c)
        if old:
            body.insert(R.randint(2, len(body)), R.choice(INTRO_OLD_AMOUNT).format(old=old))
    cut = len(body) // 2
    out += [" ".join(body[:cut]), "", " ".join(body[cut:]), ""]
    out += [f"**{R.choice(['Выход', 'Сколько получится', 'Выход блюда'])}:** {c.yield_text()}.", ""]
    out += [f"## {R.choice(['Ингредиенты', 'Продукты', 'Что понадобится'])}", ""]
    style = c.style
    listed = [i for i in c.ings if isinstance(i, tuple)
              or i.role in ("list", "opt", "alt") or (i.role == "per_serv" and getattr(i, "in_list", True))]
    groups = [""] + [g for g in c.groups_order if g != "Для подачи"] + ["Для подачи"]
    for g in groups:
        items = [i for i in listed if not isinstance(i, tuple) and i.group == g]
        if g == "":
            items += [i for i in listed if isinstance(i, tuple)]
        if not items:
            continue
        if g:
            out += ["", f"*{g}:*"]
        for i in items:
            if isinstance(i, tuple):
                labels = i[1]
                t = ", ".join(labels) if len(labels) < 3 else ", ".join(labels[:-1]) + " и " + labels[-1]
                out.append(f"- {_cap(t)} — по вкусу" if style != "B" else f"- {t} по вкусу")
            else:
                out.append(_list_line(i, style))
    out += ["", f"## {R.choice(['Приготовление', 'Как готовить', 'Ход работы'])}", ""]
    fillers = R.sample(STEP_FILLERS, k=len(STEP_FILLERS))
    for n, s in enumerate(c.steps, 1):
        if R.random() < 0.8:
            for _ in range(R.choice([1, 1, 2])):
                s = s + " " + fillers.pop()
        out.append(f"{n}. {s}")
    out += ["", f"## {R.choice(['Советы и варианты', 'Хозяйке на заметку', 'Варианты и советы'])}", ""]
    tips = list(c.tips) + R.sample(TIPS_GENERIC, k=R.randint(2, 4))
    R.shuffle(tips)
    out += [f"- {t}" for t in tips]
    out += ["", f"## {R.choice(['Что может пойти не так', 'Если что-то не получилось'])}", ""]
    out += [f"- {t}" for t in R.sample(TROUBLE[c.section], k=3)]
    out += ["", f"## {R.choice(['Из писем читателей', 'Нам пишут'])}", ""]
    for _ in range(R.randint(2, 3)):
        parts = [R.choice(LETTER_OPEN)]
        old = _old_amount(c) if R.random() < 0.6 else None
        plain = R.sample(LETTER_BODY_PLAIN, k=2)
        parts.append(R.choice(LETTER_BODY).format(alt=old) if old else plain[1])
        parts.append(plain[0])
        parts.append(R.choice(LETTER_CLOSE))
        who = f"{R.choice(READER_NAMES)} из {R.choice(READER_CITIES)}"
        out.append(f"> «{' '.join(p for p in parts if p)}» — {who}")
        out.append("")
    out += ["", f"*Заметка на полях.* {' '.join(R.sample(NOTES_GENERIC, k=R.randint(2, 4)))}", ""]
    out += [f"*Хранение.* {R.choice(STORAGE[c.section])}", ""]
    return "\n".join(out)


