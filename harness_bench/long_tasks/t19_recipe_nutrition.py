ERRATA_DATES = ["14 января 2025 г.", "3 марта 2025 г.", "22 апреля 2025 г.", "9 июня 2025 г.",
                "1 сентября 2025 г."]


def _alt_q(c: Ctx, ing: Ing):
    if ing.unit == "glass":
        return [q for q in GLASS_WORDS if q != ing.q and abs(float(q - ing.q)) <= 1]
    if ing.unit in ("g", "ml"):
        base = int(ing.q)
        return [x for x in (base - base // 4, base + base // 4, base + base // 2, base * 2)
                if x > 0 and x != base and x % 5 == 0]
    if ing.unit in ("tbsp", "tsp"):
        return [q for q in (ing.q + 1, ing.q + 2, ing.q - 1) if q >= 1 and q != ing.q]
    if ing.unit == "pcs":
        return [q for q in (ing.q + 1, ing.q + 2, ing.q - 1) if q >= 1 and q != ing.q]
    return []


def _rel_change(a, b) -> float:
    return max(abs(x - y) / max(abs(y), 1.0) for x, y in zip(a, b, strict=True))


def make_errata(R, recipes):
    """Mutate printed quantities; return errata entries [(date_idx, text)]."""
    entries = []
    pool = list(recipes)
    R.shuffle(pool)
    n_ing, n_yield = 0, 0
    for c in pool:
        if n_ing >= 30 and n_yield >= 6:
            break
        truth = c.totals()
        if n_yield < 6 and c.yield_kind in ("portions", "pieces") and R.random() < 0.3:
            alt = c.servings + R.choice([-2, 2, 4]) if c.servings > 3 else c.servings + 2
            c.printed_servings = alt
            unit = {"portions": ("порцию", "порции", "порций"),
                    "pieces": c.yield_args}[c.yield_kind]
            d = R.randrange(len(ERRATA_DATES))
            entries.append((d, f"Рецепт {c.rid} «{c.title}»: в строке выхода напечатано {alt}, верно — "
                               f"{c.servings} {unit[plural_idx(c.servings)]}."))
            n_yield += 1
            continue
        if n_ing >= 30:
            continue
        cands = [i for i in c.ings if not isinstance(i, tuple) and i.role == "list" and i.parts_g == 0
                 and i.unit in ("glass", "g", "ml", "tbsp", "tsp", "pcs")]
        R.shuffle(cands)
        for ing in cands:
            alts = _alt_q(c, ing)
            R.shuffle(alts)
            ok = None
            for q in alts:
                ing.printed_q = q
                if _rel_change(c.totals(errata=False), truth) > 0.06:
                    ok = q
                    break
                ing.printed_q = None
            if ok is None:
                continue
            nom = USED[ing.key][1]
            if ing.key == "egg":
                nom = "яйца"
            txt = ing.phrase if c.style == "B" else ing.measure_text
            printed = txt(ok)
            right = txt(ing.q)
            where = R.choice(["в списке продуктов", "в перечне ингредиентов"])
            d = R.randrange(1, len(ERRATA_DATES))
            if R.random() < 0.18:
                others = [q for q in alts if q != ok]
                if others:
                    mid = txt(others[0])
                    entries.append((R.randrange(d), f"Рецепт {c.rid} «{c.title}»: {where} для продукта "
                                                   f"«{nom}» напечатано «{printed}», следует читать "
                                                   f"«{mid}»."))
                    entries.append((d, f"Рецепт {c.rid} «{c.title}»: уточнение к прежнему исправлению — "
                                       f"для продукта «{nom}» верное количество «{right}» (а не «{mid}» "
                                       f"и не «{printed}», как напечатано)."))
                    n_ing += 1
                    break
            entries.append((d, f"Рецепт {c.rid} «{c.title}»: {where} для продукта «{nom}» напечатано "
                               f"«{printed}», следует читать «{right}»."))
            n_ing += 1
            break
    # distractors that do not affect nutrition
    for c in R.sample(recipes, 12):
        kind = R.randrange(4)
        if kind == 0:
            t = f"Рецепт {c.rid} «{c.title}»: в шаге 2 вместо «на сильном огне» следует читать «на среднем огне»."
        elif kind == 1:
            t = f"Рецепт {c.rid} «{c.title}»: время на последнем шаге указано ориентировочно; при слабой плите " \
                "добавьте 5–10 минут."
        elif kind == 2:
            t = f"Рецепт {c.rid}: в оглавлении название напечатано с опечаткой, правильно — «{c.title}»."
        else:
            t = f"Рецепт {c.rid} «{c.title}»: в разделе советов речь идёт о варианте, а не об основном рецепте; " \
                "количества в списке продуктов верны."
        entries.append((R.randrange(len(ERRATA_DATES)), t))
    return entries


def render_errata(R, entries) -> str:
    out = ["# Исправления к изданию", "",
           "После выхода книги редакция рассылала читателям листки-вкладыши с исправлениями. Ниже они "
           "собраны по датам. Исправления относятся к напечатанному тексту рецептов: если исправлено "
           "количество продукта или выход, считать нужно по исправленному значению. Если к одному и "
           "тому же месту есть несколько исправлений, действует более позднее.", ""]
    for d, date in enumerate(ERRATA_DATES):
        items = [t for dd, t in entries if dd == d]
        if not items:
            continue
        R.shuffle(items)
        out += [f"## Вкладыш от {date}", ""]
        out += [f"- {t}" for t in items]
        out.append("")
    return "\n".join(out)


