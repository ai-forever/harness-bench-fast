def plural_idx(n: int) -> int:
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return 0
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return 1
    return 2


def fmt_dec(x: float) -> str:
    """Russian decimal: 1.5 -> «1,5», 2.0 -> «2»."""
    x = round(float(x), 3)
    return (str(int(x)) if x == int(x) else f"{x:g}").replace(".", ",")


FRAC_SIGN = {Fraction(1, 4): "¼", Fraction(1, 3): "⅓", Fraction(1, 2): "½", Fraction(2, 3): "⅔",
             Fraction(3, 4): "¾"}


def frac_text(q: Fraction) -> str:
    whole, part = divmod(q, 1)
    whole = int(whole)
    if part == 0:
        return str(whole)
    sign = FRAC_SIGN[Fraction(part)]
    return f"{whole}{sign}" if whole else sign


