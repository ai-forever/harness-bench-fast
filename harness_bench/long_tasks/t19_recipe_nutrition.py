def spoon_text(q: Fraction, kind: str, words: bool) -> str:
    """kind: 'tbsp' | 'tsp'."""
    if not words or q.denominator != 1 or q > 4:
        return f"{frac_text(q)} {'ст. л.' if kind == 'tbsp' else 'ч. л.'}"
    adj = ("столовая", "столовые", "столовых") if kind == "tbsp" else ("чайная", "чайные", "чайных")
    noun = ("ложка", "ложки", "ложек")
    n = int(q)
    i = plural_idx(n)
    return f"{n} {adj[i]} {noun[i]}"


