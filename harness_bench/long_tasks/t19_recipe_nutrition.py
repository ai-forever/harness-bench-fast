PROMPT = """\
В каталоге `cookbook/` — домашняя кулинарная книга: предисловие с соглашениями и правилами расчёта
(`cookbook/preface.md`), рецепты (`cookbook/recipes/rNNN.md`) и вкладыши с исправлениями
(`cookbook/errata.md`). В `reference/` — перевод бытовых мер в граммы (`measures.md`) и пищевая
ценность продуктов на 100 г с синонимами названий (`nutrition.csv`).

Посчитайте пищевую ценность одной порции каждого рецепта книги и запишите её в `nutrition.csv` в корне
рабочего каталога: заголовок `recipe_id,kcal,protein,fat,carbs`, далее по строке на каждый рецепт —
идентификатор рецепта (`r001`, …), калории, белки, жиры и углеводы на одну порцию, с одним знаком
после запятой (десятичный разделитель — точка).

Что входит в расчёт, какие меры приняты в книге и как определять число порций, написано в
предисловии; исправления из вкладышей имеют приоритет над текстом рецептов. Рецептов много, написаны
они свободным языком, и в каждом важны детали — в том числе то, что сказано только в шагах
приготовления.
"""


def _setup(ws: Path) -> None:
    for rel, text in build()["files"].items():
        write(ws, rel, text)


def _write_answers(ws: Path, rows: dict[str, tuple]) -> None:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["recipe_id", "kcal", "protein", "fat", "carbs"])
    for rid in sorted(rows):
        w.writerow([rid, *(f"{v:.1f}" for v in rows[rid])])
    write(ws, "nutrition.csv", buf.getvalue())


def _gold(ws: Path) -> None:
    _write_answers(ws, build()["truth"])


def _ok(got: float, exp: float) -> bool:
    return abs(got - exp) <= max(0.03 * abs(exp), 0.1)


def _share_ok(rows: dict[str, tuple]) -> float:
    truth = build()["truth"]
    good = sum(1 for rid, exp in truth.items()
               if rid in rows and all(_ok(g, e) for g, e in zip(rows[rid], exp, strict=True)))
    return good / len(truth)


def _check(ws: Path) -> str:
    truth = build()["truth"]
    rows = read_csv(ws, "nutrition.csv", required=("recipe_id", "kcal", "protein", "fat", "carbs"))
    got = {}
    for row in rows:
        rid = row["recipe_id"].strip().lower()
        vals = [num(row[k]) for k in ("kcal", "protein", "fat", "carbs")]
        if None not in vals:
            got[rid] = tuple(vals)
    good, errors = 0, []
    for rid, exp in sorted(truth.items()):
        g = got.get(rid)
        if g is None:
            errors.append(f"{rid}: нет строки")
            continue
        bad = [name for name, a, e in zip(("kcal", "protein", "fat", "carbs"), g, exp, strict=True)
               if not _ok(a, e)]
        if bad:
            errors.append(f"{rid}: {', '.join(bad)} вне допуска")
        else:
            good += 1
    return require_share(len(truth), good, min_share=0.9, what="рецепты (все 4 значения в ±3 %)",
                         errors=errors)


def _variant_rows(**kw) -> dict[str, tuple]:
    return {c.rid: c.totals(**kw) for c in build()["recipes"]}


def _nm_glass_250(ws: Path) -> None:
    """Every glass taken as 250 ml."""
    _write_answers(ws, _variant_rows(glass250=True))


def _nm_count_variants(ws: Path) -> None:
    """Optional items, alternative variants and suggestions from the tips are counted."""
    _write_answers(ws, _variant_rows(variants=True))


def _nm_ignore_steps(ws: Path) -> None:
    """Only the ingredient list is read; quantities introduced in the steps are lost."""
    rows = {}
    for c in build()["recipes"]:
        saved = [(i, i.role) for i in c.ings if not isinstance(i, tuple)
                 and (i.role in ("step_new", "step_extra")
                      or (i.role == "per_serv" and not getattr(i, "in_list", True)))]
        for i, _ in saved:
            i.role = "dropped"
        rows[c.rid] = c.totals()
        for i, role in saved:
            i.role = role
    _write_answers(ws, rows)


def _nm_per_recipe(ws: Path) -> None:
    """Totals for the whole recipe instead of one serving."""
    _write_answers(ws, _variant_rows(divide=False))


def _nm_ignore_errata(ws: Path) -> None:
    """Printed quantities and yields, errata not applied."""
    _write_answers(ws, _variant_rows(errata=False))


def _nm_double_count_parts(ws: Path) -> None:
    """Every number in the steps added on top of the list («200 г муки… оставшиеся 120 г»)."""
    _write_answers(ws, _variant_rows(parts=True))


def _nm_naive_all(ws: Path) -> None:
    """Keyword-style reading: 250 ml glass, everything mentioned counted, no errata."""
    _write_answers(ws, _variant_rows(glass250=True, variants=True, errata=False, parts=True))


