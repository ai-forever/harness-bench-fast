def _lm_canon(ref: tuple[str, str]) -> str:
    return ref[1]  # тип («аптека») или id («L05»)


def _canon_step(st: dict) -> dict:
    t = st["t"]
    kind = {"nth": "cross", "turnth": "turn", "lm": "landmark", "to_street": "street", "intent": "cancelled",
            "stop_next": "stop_blocks", "stop_lm": "stop_landmark"}.get(t, t)
    out: dict = {"t": kind}
    if t == "stop_next":
        out["n"] = 1
    if "n" in st:
        out["n"] = st["n"]
    if "side" in st:
        out["side"] = st["side"]
    if "ref" in st:
        out["lm"] = _lm_canon(st["ref"])
    if "street" in st:
        out["street"] = sname(st["street"])
    if st.get("corr"):
        field = _FIELD[st["ckind"]]
        was = st["w" + st["ckind"]]
        out["fix"] = {"field": field, "was": _lm_canon(was) if field == "lm" else was, "late": st["corr"] == "late"}
    return out


def _fold(steps: list[dict]) -> list[dict]:
    """«Проехал два квартала. Там же и отдал» и «через два квартала отдал» — один и тот же финал."""
    if len(steps) >= 2 and steps[-1] == {"t": "stop_here"} and steps[-2]["t"] == "blocks":
        return steps[:-2] + [dict(steps[-2], t="stop_blocks")]
    return steps


def _street_key(name: str) -> tuple[str, int]:
    return next(k for k in [("V", i) for i in range(NX)] + [("H", j) for j in range(NY)] if sname(k) == name)


def _internal(cs: dict) -> dict:
    """Шаг канонического списка → шаг интерпретатора `Walker`."""
    t = cs["t"]
    st: dict = {"t": {"cross": "nth", "turn": "turnth", "landmark": "lm", "street": "to_street",
                      "cancelled": "intent", "stop_landmark": "stop_lm"}.get(t, t)}
    for k in ("n", "side"):
        if k in cs:
            st[k] = cs[k]
    if "lm" in cs:
        st["ref"] = ("name", cs["lm"]) if re.fullmatch(r"L\d\d", cs["lm"]) else ("type", cs["lm"])
    if "street" in cs:
        st["street"] = _street_key(cs["street"])
    return st


def _canon_route(route: dict) -> dict:
    """Канонический маршрут и пометки-ловушки к каждому шагу (что изменится при неверном прочтении)."""
    _n, x, y = DEPOTS[route["depot"]]
    w = Walker(x, y, route["h"], route["day"], frozenset())
    steps, notes = [], []
    for st in route["steps"]:
        gold_st = _step_alt(w, st, frozenset())
        why = []
        if st["t"] == "turnth" and any(_step_alt(w, st, MODES[m]) != gold_st for m in ("count_all", "turn_nocl")):
            why.append("счёт всех перекрёстков или без учёта перекрытий дал бы другое место — фраза должна "
                       "однозначно считать именно повороты")
        if st["t"] == "lm" and st["ref"][0] == "type" and _step_alt(w, st, MODES["lm_nodates"]) != gold_st:
            why.append("раньше по пути есть такой же ориентир, закрытый в эту дату — называй только тип")
        if st.get("corr") and _step_alt(w, st, MODES["nocorr"]) != gold_st:
            why.append("без поправки выйдет другое место")
        steps.append(_canon_step(st))
        notes.append("; ".join(why))
        w.run_step(st)
    folded = _fold(steps)
    if len(folded) < len(steps):
        notes = notes[:-2] + ["; ".join(filter(None, notes[-2:]))]
    return {"depot": DEPOTS[route["depot"]][0], "dir": route["h"], "steps": folded, "notes": notes}


def _run_canon(canon: dict, day: date) -> tuple[int, int] | None:
    """Исполнить канонический маршрут по правилам; None — неисполним."""
    dep = next((d_ for d_ in DEPOTS if d_[0] == canon["depot"]), None)
    if dep is None or canon["dir"] not in VEC:
        return None
    w = Walker(dep[1], dep[2], canon["dir"], day, frozenset())
    try:
        for cs in canon["steps"]:
            w.run_step(_internal(cs))
    except (Illegal, KeyError, StopIteration, TypeError):
        return None
    return (w.x, w.y)


