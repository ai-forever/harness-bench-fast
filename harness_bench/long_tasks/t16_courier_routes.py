@functools.cache
def _mention_rx() -> list[tuple[re.Pattern, str]]:
    out = []
    for key in [("V", i) for i in range(NX)] + [("H", j) for j in range(NY)]:
        words = sorted({_e(f.split()[0]) for f in sforms(key).values()}, key=len, reverse=True)
        out.append((re.compile(r"(?<![«\w])(" + "|".join(words) + r")(?![\w»])"), sname(key)))
    return out


_DEPOT_RX = re.compile(r"«\w+»|\bсклад\w*\s+\w+|\w+\s+склад\w*")


def _mentions(text: str) -> set[str]:
    """Улицы, названные в тексте в любом падеже (названия складов — «Речной», «Северный» — не в счёт)."""
    text = _DEPOT_RX.sub(" ", _e(text))
    return {name for rx, name in _mention_rx() if rx.search(text)}


