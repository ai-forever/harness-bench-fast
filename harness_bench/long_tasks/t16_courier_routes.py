def _pick(R: random.Random, lst: list[str], n: int | None = None, lmref: tuple | None = None) -> str:
    cands = []
    for t in lst:
        body, _, tag = t.partition("@")
        if tag == "1" and n != 1 or tag == "2" and (n is None or n < 2):
            continue
        if tag == "type" and (lmref is None or lmref[0] != "type"):
            continue
        cands.append(body)
    return R.choice(cands)


def _nkw(n: int, prefix: str = "") -> dict[str, str]:
    o = ORD[n]
    return {f"{prefix}o_n": o[0], f"{prefix}o_g": o[1], f"{prefix}o_p": o[2], f"{prefix}v_o": v_in(o[0]),
            f"{prefix}blk": cnt(n, "квартал", "квартала", "кварталов")}


def step_text(R: random.Random, V: Voice, st: dict, w: Walker) -> tuple[str, str | None]:
    """Фраза шага и (для поздней поправки) фраза-поправка."""
    t = st["t"]
    corr, ck = st.get("corr"), st.get("ckind")
    late = corr == "late"
    n = st.get("n")
    shown_n = st.get("wn", n) if late else n
    side = st.get("side")
    shown_side = st.get("wside", side) if late else side
    kw: dict[str, str] = {}
    if n is not None:
        kw.update(_nkw(shown_n))
        if "wn" in st:
            kw.update(_nkw(st["wn"], "w"))
    if side:
        kw["side"] = SIDE[shown_side]
        if "wside" in st:
            kw["wside"] = SIDE[st["wside"]]
    if "ref" in st:
        kw.update(lm_ref_forms(st["ref"]))
        if "wref" in st:
            kw.update({"w" + k: v for k, v in lm_ref_forms(st["wref"]).items()})
    if "street" in st:
        kw.update(st_kw(st["street"]))
    fix = None
    if corr == "imm":
        if t == "nth":
            tpl = R.choice(T_FIX_N if ck == "n" else T_FIX_SIDE)
        elif t == "turnth":
            tpl = R.choice(T_FIX_T)
        elif t in ("blocks", "stop_blocks"):
            tpl = R.choice(T_FIX_B)
            if t == "stop_blocks":
                tpl += " Там и {V:встал|встала} — адрес на углу."
        elif t == "lm":
            tpl = R.choice(T_FIX_LM)
        else:
            raise AssertionError(t)
        return V.say(tpl, **kw), None
    if t == "nth":
        if shown_n > 1:
            kw["skip_x"] = cnt(shown_n - 1, "перекрёсток", "перекрёстка", "перекрёстков")
        tpl = _pick(R, T_NTH, shown_n)
    elif t == "turnth":
        if shown_n > 1:
            kw["skip_t"] = cnt(shown_n - 1, "поворот", "поворота", "поворотов")
        tpl = _pick(R, T_TURNTH, shown_n)
    elif t == "lm":
        tpl = _pick(R, T_LM, lmref=st["ref"])
    elif t == "to_street":
        tpl = R.choice(T_TO_STREET)
    elif t == "blocks":
        tpl = R.choice(T_BLOCKS)
    elif t == "uturn":
        tpl = R.choice(T_UTURN)
    elif t == "end":
        kw.update(st_kw(street_of(w.x, w.y, w.h)))
        tpl = R.choice(T_END)
    elif t == "intent":
        tpl = R.choice(T_INTENT)
    else:
        tpl = R.choice(T_STOP[t])
    if late:
        if t == "nth" and ck == "n":
            wphr, rphr = f"{ORD[st['wn']][0]} перекрёсток", f"{ORD[n][0]}, а не {ORD[st['wn']][0]}"
        elif t == "nth":
            wphr, rphr = f"{ORD[n][0]} перекрёсток {SIDE[st['wside']]}", SIDE[side]
        elif t == "turnth":
            wphr = f"{ORD[st['wn']][0]} поворот {SIDE[side]}"
            rphr = f"{ORD[n][0]} поворот, а не {ORD[st['wn']][0]}"
        else:
            wphr = cnt(st["wn"], "квартал", "квартала", "кварталов")
            rphr = cnt(n, "квартал", "квартала", "кварталов")
        fix = V.say(R.choice(T_LATE), wphr=wphr, rphr=rphr)
    return V.say(tpl, **kw), fix


def _street_pool(R: random.Random, avoid: set) -> dict[str, str]:
    allk = [("V", i) for i in range(NX)] + [("H", j) for j in range(NY)]
    keys = [k for k in allk if k not in avoid]
    a = R.choice(keys)
    b = R.choice([k for k in keys if k[0] != a[0]] or [k for k in allk if k[0] != a[0]])
    out = {}
    for pre, key in (("s1", a), ("s2", b)):
        out.update({f"{pre}_{c}": v for c, v in sforms(key).items()})
    return out


def route_streets(route: dict) -> set:
    _n, x, y = DEPOTS[route["depot"]]
    w = Walker(x, y, route["h"], route["day"], frozenset())
    seen = {("V", x), ("H", y)}
    for st in route["steps"]:
        w.passed = []
        w.run_step(st)
        for px, py in w.passed:
            seen.update({("V", px), ("H", py)})
    return seen


def render_note(R: random.Random, nid: str, route: dict) -> str:
    courier, g = COURIERS[route["courier"]]
    V = Voice(R, g)
    day: date = route["day"]
    order = f"{R.randint(1000, 9999)}-{R.randint(100, 999)}"
    dep, x, y = DEPOTS[route["depot"]]
    avoid = route_streets(route)
    chat = R.sample(CHAT, len(CHAT))
    stories = R.sample(STORIES, len(STORIES))
    weather_used = False

    def chat_line() -> str | None:
        nonlocal weather_used
        while chat:
            c = chat.pop()
            if c.startswith(("Жара", "Дождь", "Солнце", "По радио сказали")):
                if weather_used:
                    continue
                weather_used = True
            return V.filler(V.say(c), 0.25, CHAT_FILLERS)
        return None

    def story_line() -> str:
        return V.filler(V.say(stories.pop(), **_street_pool(R, avoid)), 0.2, CHAT_FILLERS)

    def distract_line() -> str:
        return V.filler(V.say(R.choice(DISTRACT), **_street_pool(R, avoid)), 0.2, CHAT_FILLERS)

    head_sent = [V.say(R.choice(OPENERS), order=order, courier=courier)]
    for _ in range(R.randint(1, 2)):
        head_sent.append(chat_line())
    w = Walker(x, y, route["h"], day, frozenset())
    kw = st_kw(street_of(x, y, route["h"]))
    kw.update(dep=dep, dirw=R.choice(DIRW[route["h"]]), a_g=sforms(("V", x))["g"], b_g=sforms(("H", y))["g"])
    body = [V.filler(V.say(R.choice(T_START), **kw), 0.3, CHAT_FILLERS)]
    pending: list[tuple[int, str]] = []
    steps = route["steps"]
    final_idx = 0
    for i, st in enumerate(steps):
        text, fix = step_text(R, V, st, w)
        if i == len(steps) - 1:
            final_idx = len(body)
        body.append(V.filler(text))
        if fix:
            pending.append((i + R.randint(1, 3), fix))
        for due, f in list(pending):
            if due == i and i < len(steps) - 1:
                body.append(f)
                pending.remove((due, f))
        w.run_step(st)
    body.extend(f for _due, f in pending)
    # шум: реплики, истории и отвлекающие упоминания улиц между шагами маршрута
    noise = [distract_line() for _ in range(R.choice([1, 1, 2, 2, 3]))]
    noise += [story_line() for _ in range(R.choice([1, 2, 2, 3]))]
    target = R.randint(2200, 2950)
    total = sum(map(len, head_sent + body + noise))
    while total < target and chat:
        line = chat_line()
        if line:
            noise.append(line)
            total += len(line)
    R.shuffle(noise)
    for line in noise:
        # не вставлять шум прямо перед финальной фразой: она может ссылаться на предыдущую («там же»)
        pos = R.choice([p for p in range(1, len(body) + 1) if p != final_idx])
        body.insert(pos, line)
        if pos < final_idx:
            final_idx += 1
    tail = [chat_line() or "", V.say(R.choice(CLOSERS))]
    sent = [x_ for x_ in head_sent + body + tail if x_]
    paras, cur = [], []
    for s_ in sent:
        cur.append(s_)
        if len(cur) >= R.randint(3, 6):
            paras.append(" ".join(cur))
            cur = []
    if cur:
        paras.append(" ".join(cur))
    head = [f"# Голосовая заметка {nid}", "",
            f"- Дата: {day.day} {MONTHS[day.month]} {day.year} г., {WEEKDAYS[day.weekday()]}",
            f"- Курьер: {courier}",
            f"- Заказ: {order}",
            "- Расшифровка автоматическая, без редактуры", ""]
    return "\n".join(head) + "\n" + "\n\n".join(paras) + "\n"


