def street_of(x: int, y: int, dr: str) -> tuple[str, int]:
    return ("V", x) if dr in ("N", "S") else ("H", y)


def seg_closed(x: int, y: int, dr: str, day: date) -> bool:
    key = street_of(x, y, dr)
    dx, dy = VEC[dr]
    a = y if key[0] == "V" else x
    b = a + (dy if key[0] == "V" else dx)
    lo, hi = min(a, b), max(a, b)
    for skey, fa, fb, s, e in CLOSURES:
        if skey == key and s <= day <= e and fa <= lo and hi <= fb:
            return True
    return False


def in_grid(x: int, y: int) -> bool:
    return 0 <= x < NX and 0 <= y < NY


def seg_exists(x: int, y: int, dr: str) -> bool:
    dx, dy = VEC[dr]
    return in_grid(x + dx, y + dy)


def seg_ok(x: int, y: int, dr: str, day: date, *, closures: bool = True, one_way: bool = True) -> bool:
    if not seg_exists(x, y, dr):
        return False
    key = street_of(x, y, dr)
    if one_way and key in ONE_WAY and ONE_WAY[key] != dr:
        return False
    return not (closures and seg_closed(x, y, dr, day))


