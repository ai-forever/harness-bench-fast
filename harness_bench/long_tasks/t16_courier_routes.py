_TYPE_WORDS = re.compile(r"\b(улица|ул|проспект|просп|пр-т|пр|бульвар|бул|б-р|переулок|пер|пер-к)\b\.?")


def _skey(s: str) -> str:
    t = s.replace("ё", "е").replace("Ё", "Е").casefold()
    t = _TYPE_WORDS.sub(" ", t)
    t = re.sub(r"[^\w\s-]", " ", t)
    return re.sub(r"\s+", " ", t).strip()


def _street_index() -> dict[str, tuple[str, int]]:
    out = {}
    for i, (name, _g) in enumerate(VERT):
        out[_skey(name)] = ("V", i)
    for j, (name, _g) in enumerate(HOR):
        out[_skey(name)] = ("H", j)
    return out


def check(ws: Path) -> str:
    w = build()
    for rel, text in _inputs().items():
        p = ws / rel
        assert p.is_file() and p.read_text(encoding="utf-8") == text, f"входной файл {rel} изменён"
    rows = read_csv(ws, "deliveries.csv", ["note_id", "street_a", "street_b"])
    idx = _street_index()
    got: dict[str, frozenset] = {}
    for r in rows:
        m = re.search(r"(\d+)", r["note_id"])
        if not m:
            continue
        nid = f"n{int(m.group(1)):03d}"
        got[nid] = frozenset(filter(None, (idx.get(_skey(r["street_a"])), idx.get(_skey(r["street_b"])))))
    ok, errors = 0, []
    for n in w["notes"]:
        x, y = n["answer"]
        if got.get(n["id"]) == frozenset({("V", x), ("H", y)}):
            ok += 1
        else:
            errors.append(f"{n['id']}: {'нет строки' if n['id'] not in got else 'неверно'}")
    return require_share(len(w["notes"]), ok, min_share=MIN_SHARE, what="перекрёстки доставки", errors=errors)


