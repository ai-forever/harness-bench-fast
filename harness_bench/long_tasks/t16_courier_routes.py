class Illegal(Exception):
    """Шаг невозможен по правилам (в строгом режиме)."""


def lm_match(lm: tuple, ref: tuple[str, str]) -> bool:
    kind, val = ref
    return lm[1] == val if kind == "type" else lm[0] == val


def turn_ok(x: int, y: int, dr: str, day: date, mode: frozenset) -> bool:
    if "count_all" in mode:
        return seg_exists(x, y, dr)
    return seg_ok(x, y, dr, day, closures="turn_nocl" not in mode)


class Walker:
    def __init__(self, x: int, y: int, h: str, day: date, mode: frozenset):
        self.x, self.y, self.h, self.day, self.mode = x, y, h, day, mode
        self.strict = not mode
        self.passed: list[tuple[int, int]] = []

    def fwd(self) -> None:
        if self.strict and not seg_ok(self.x, self.y, self.h, self.day):
            raise Illegal("fwd")
        if not seg_exists(self.x, self.y, self.h):
            raise Illegal("edge")
        dx, dy = VEC[self.h]
        self.x, self.y = self.x + dx, self.y + dy
        self.passed.append((self.x, self.y))

    def turn(self, side: str) -> None:
        nd = RIGHT[self.h] if side == "R" else LEFT[self.h]
        if self.strict and not seg_ok(self.x, self.y, nd, self.day):
            raise Illegal("turn")
        self.h = nd

    def val(self, step: dict, key: str):
        if "nocorr" in self.mode and ("w" + key) in step:
            return step["w" + key]
        return step[key]

    def run_step(self, st: dict) -> None:
        t = st["t"]
        if t in ("nth", "blocks", "stop_blocks"):
            for _ in range(self.val(st, "n")):
                self.fwd()
            if t == "nth":
                self.turn(self.val(st, "side"))
        elif t == "stop_next":
            self.fwd()
        elif t == "turnth":
            n, side = self.val(st, "n"), self.val(st, "side")
            cnt = 0
            while True:
                self.fwd()
                nd = RIGHT[self.h] if side == "R" else LEFT[self.h]
                if turn_ok(self.x, self.y, nd, self.day, self.mode):
                    cnt += 1
                    if cnt == n:
                        break
            self.turn(side)
        elif t in ("lm", "stop_lm"):
            ref = self.val(st, "ref")
            while True:
                self.fwd()
                lm = LM_AT.get((self.x, self.y))
                if lm and lm_match(lm, ref) and ("lm_nodates" in self.mode or lm_valid(lm, self.day)):
                    break
            if t == "lm":
                self.turn(self.val(st, "side"))
        elif t in ("to_street", "stop_street"):
            key = st["street"]
            while (self.x if key[0] == "V" else self.y) != key[1]:
                self.fwd()
            if t == "to_street":
                self.turn(self.val(st, "side"))
        elif t == "uturn":
            nd = BACK[self.h]
            if self.strict and not seg_ok(self.x, self.y, nd, self.day):
                raise Illegal("uturn")
            self.h = nd
        elif t == "end":
            while seg_exists(self.x, self.y, self.h):
                self.fwd()
        elif t == "stop_here":
            pass
        elif t == "intent":  # несостоявшийся поворот: ничего не делает
            if "intent_exec" in self.mode:
                self.turn(st["side"])
        else:
            raise AssertionError(t)


def execute(route: dict, mode: frozenset = frozenset()) -> tuple[int, int] | None:
    """Перекрёсток доставки при данном прочтении правил (None — маршрут не исполним)."""
    _name, x, y = DEPOTS[route["depot"]]
    w = Walker(x, y, route["h"], route["day"], mode)
    try:
        for st in route["steps"]:
            w.run_step(st)
    except Illegal:
        if not mode:
            raise
        return None
    return (w.x, w.y)


