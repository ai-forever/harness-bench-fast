_GSLOT = re.compile(r"\{V:([^|{}]*)\|([^{}]*)\}")


class Voice:
    """Рендер фраз от лица курьера нужного рода."""

    def __init__(self, R: random.Random, gender: str):
        self.R, self.g = R, gender

    def say(self, tpl: str, **kw: str) -> str:
        text = _GSLOT.sub(lambda m: m.group(1) if self.g == "m" else m.group(2), tpl)
        text = text.format(**kw) if kw else text
        return text[0].upper() + text[1:]

    def filler(self, text: str, p: float = 0.35, pool: list[str] | None = None) -> str:
        if self.R.random() < p and not text.startswith(("Потом", "Дальше", "Тут", "Там")):
            f = self.R.choice(pool or FILLERS)
            return f + text[0].lower() + text[1:] if not text.startswith("«") else f + text
        return text


def lm_ref_forms(ref: tuple[str, str]) -> dict[str, str]:
    kind, val = ref
    if kind == "type":
        n, g, a = LM_TYPES[val]
        return dict(lm_n=n, lm_g=g, lm_a=a)
    lm = next(x for x in LANDMARKS if x[0] == val)
    return dict(lm_n=lm[2][0], lm_g=lm[2][1], lm_a="")


def st_kw(key: tuple[str, int], prefix: str = "st") -> dict[str, str]:
    f = sforms(key)
    return {f"{prefix}_{c}": v for c, v in f.items()} | {f"{prefix}_pron": "неё" if sgender(key) == "f" else "него"}


