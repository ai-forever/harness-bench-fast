def _try(w: Walker, st: dict) -> Walker | None:
    w2 = Walker(w.x, w.y, w.h, w.day, frozenset())
    try:
        w2.run_step(st)
    except Illegal:
        return None
    return w2


def _step_alt(w: Walker, st: dict, mode: frozenset) -> tuple | None:
    w2 = Walker(w.x, w.y, w.h, w.day, mode)
    try:
        w2.run_step(st)
    except Illegal:
        return None
    return (w2.x, w2.y, w2.h)


def _ahead(w: Walker, k: int) -> list[tuple[int, int]]:
    out, x, y = [], w.x, w.y
    dx, dy = VEC[w.h]
    for _ in range(k):
        x, y = x + dx, y + dy
        if not in_grid(x, y):
            break
        out.append((x, y))
    return out


def rand_step(R: random.Random, w: Walker, kind: str) -> dict | None:
    side = R.choice("RL")
    if kind == "nth":
        return dict(t="nth", n=R.choice([1, 1, 2, 2, 3, 4]), side=side)
    if kind == "turnth":
        return dict(t="turnth", n=R.choice([1, 2, 2, 3, 3]), side=side)
    if kind == "lm_trap":
        seen_bad: set[str] = set()
        for p in _ahead(w, 11):
            lm = LM_AT.get(p)
            if not lm:
                continue
            if not lm_valid(lm, w.day):
                seen_bad.add(lm[1])
            elif lm[1] in seen_bad:
                return dict(t="lm", ref=("type", lm[1]), side=side)
        return None
    if kind == "lm":
        cands = [LM_AT[p] for p in _ahead(w, 6) if p in LM_AT and lm_valid(LM_AT[p], w.day)]
        if not cands:
            return None
        lm = R.choice(cands)
        ref = ("type", lm[1]) if R.random() < 0.7 else ("name", lm[0])
        return dict(t="lm", ref=ref, side=side)
    if kind == "to_street":
        pts = _ahead(w, 4)
        if not pts:
            return None
        x, y = R.choice(pts)
        key = ("H", y) if w.h in ("N", "S") else ("V", x)
        return dict(t="to_street", street=key, side=side)
    if kind == "blocks":
        return dict(t="blocks", n=R.choice([1, 2, 2, 3]))
    if kind == "uturn":
        return dict(t="uturn")
    if kind == "end":
        return dict(t="end") if len(_ahead(w, 20)) <= 5 else None
    raise AssertionError(kind)


def rand_final(R: random.Random, w: Walker, last: dict) -> dict | None:
    kinds = ["stop_next", "stop_blocks", "stop_lm", "stop_street"]
    if last["t"] in ("blocks", "end", "intent"):
        kinds.append("stop_here")
    kind = R.choice(kinds)
    if kind == "stop_blocks":
        return dict(t=kind, n=R.choice([1, 2, 3]))
    if kind == "stop_lm":
        cands = [LM_AT[p] for p in _ahead(w, 5) if p in LM_AT and lm_valid(LM_AT[p], w.day)]
        if not cands:
            return None
        lm = cands[0] if R.random() < 0.5 else R.choice(cands)
        return dict(t=kind, ref=("type", lm[1]) if R.random() < 0.6 else ("name", lm[0]))
    if kind == "stop_street":
        pts = _ahead(w, 4)
        if not pts:
            return None
        x, y = R.choice(pts)
        return dict(t=kind, street=("H", y) if w.h in ("N", "S") else ("V", x))
    return dict(t=kind)


_KIND_W = [("nth", 3.0), ("turnth", 2.5), ("lm", 2.2), ("to_street", 2.0), ("blocks", 1.4), ("uturn", 0.25),
           ("end", 0.35)]


def gen_route(R: random.Random, focus: str) -> dict:
    """Случайный законный маршрут, в котором ловушка `focus` меняет итог."""
    for _attempt in range(5000):
        day = D0 + timedelta(days=R.randrange((D1 - D0).days + 1))
        depot = R.randrange(len(DEPOTS))
        _n, x, y = DEPOTS[depot]
        heads = [h for h in DIRS if seg_ok(x, y, h, day)]
        h = R.choice(heads)
        w = Walker(x, y, h, day, frozenset())
        steps: list[dict] = []
        flags: set[str] = set()
        n_steps = R.randint(5, 9)
        tries = 0
        while len(steps) < n_steps and tries < 60:
            tries += 1
            kinds, weights = zip(*_KIND_W, strict=True)
            kind = R.choices(kinds, weights)[0]
            if focus in ("turn", "turn_cl") and "turn" not in flags and R.random() < 0.5:
                kind = "turnth"
            if focus == "lm" and "lm" not in flags and R.random() < 0.7:
                kind = "lm_trap"
            if steps and steps[-1]["t"] == "uturn" and kind == "uturn":
                continue
            st = rand_step(R, w, kind)
            if st is None:
                continue
            w2 = _try(w, st)
            if w2 is None:
                continue
            if st["t"] == "turnth":
                gold = (w2.x, w2.y, w2.h)
                if _step_alt(w, st, MODES["count_all"]) != gold or _step_alt(w, st, MODES["turn_nocl"]) != gold:
                    flags.add("turn")
            if st["t"] == "lm" and _step_alt(w, st, MODES["lm_nodates"]) != (w2.x, w2.y, w2.h):
                flags.add("lm")
            steps.append(st)
            w = w2
            if st["t"] == "blocks" and len(steps) < n_steps and (
                    (focus == "intent" and "intent" not in flags) or R.random() < 0.12):
                sides = [sd for sd in "RL" if seg_ok(w.x, w.y, RIGHT[w.h] if sd == "R" else LEFT[w.h], w.day)]
                if sides:
                    steps.append(dict(t="intent", side=R.choice(sides), street=("H", w.y) if w.h in "NS" else ("V", w.x)))
                    flags.add("intent")
        if len(steps) < 4:
            continue
        fin = None
        for _ in range(10):
            fin = rand_final(R, w, steps[-1])
            if fin is not None and _try(w, fin) is not None:
                break
            fin = None
        if fin is None:
            continue
        steps.append(fin)
        route = dict(day=day, depot=depot, h=h, steps=steps)
        if focus.startswith("corr") and not add_correction(R, route, late=focus == "corr_late"):
            continue
        if focus == "corr2":
            add_correction(R, route, late=R.random() < 0.5)
        route["answer"] = execute(route)
        if route["answer"] == (x, y):
            continue
        alt = {m: execute(route, mm) for m, mm in MODES.items()}
        need = {"corr_imm": "nocorr", "corr_late": "nocorr", "turn": None, "lm": "lm_nodates",
                "intent": "intent_exec"}.get(focus)
        if focus == "turn" and alt["count_all"] == route["answer"] and alt["turn_nocl"] == route["answer"]:
            continue
        if focus == "turn_cl" and alt["turn_nocl"] == route["answer"]:
            continue
        if need and alt[need] == route["answer"]:
            continue
        route["alt"] = alt
        return route
    raise AssertionError(f"не удалось построить маршрут: {focus}")


def _sig(st: dict, n: int) -> tuple:
    return (st["t"].replace("stop_", ""), n)


def add_correction(R: random.Random, route: dict, *, late: bool) -> bool:
    """Добавить самопоправку к одному из шагов так, чтобы без неё итог был другим."""
    steps = route["steps"]
    idx = list(range(len(steps)))
    R.shuffle(idx)
    base = execute(route)
    for i in idx:
        st = steps[i]
        if "corr" in st:
            continue
        t = st["t"]
        opts = []
        if t in ("nth", "turnth", "blocks", "stop_blocks"):
            for wn in (st["n"] + 1, st["n"] - 1):
                if 1 <= wn <= 5:
                    opts.append(("n", wn))
        if t == "nth":
            opts.append(("side", "L" if st["side"] == "R" else "R"))
        if t == "lm" and not late:
            other = [tp for tp in LM_TYPES if tp != (st["ref"][1] if st["ref"][0] == "type" else "")]
            if st["ref"][0] == "type":
                opts.append(("ref", ("type", R.choice(other))))
        R.shuffle(opts)
        for ck, wv in opts:
            if late:
                if t not in ("nth", "turnth", "blocks"):
                    continue
                shown = wv if ck == "n" else st["n"]
                others = [_sig(s2, s2.get("wn", s2["n"]) if s2.get("corr") == "late" else s2["n"])
                          for j, s2 in enumerate(steps) if j != i and "n" in s2]
                if _sig(st, shown) in others or (ck == "side" and _sig(st, st["n"]) in others):
                    continue
            trial = dict(st)
            trial["w" + ck] = wv
            trial["corr"] = "late" if late else "imm"
            trial["ckind"] = ck
            steps[i] = trial
            if execute(route, MODES["nocorr"]) != base:
                return True
            steps[i] = st
    return False


