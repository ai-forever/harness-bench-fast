def street_forms(name: str) -> dict[str, str]:
    words = name.split()
    adj = words[0]
    if len(words) == 1:  # женский род: Садовая
        s = adj[:-2]
        return dict(zip(CASES, (adj, s + "ую", s + "ой", s + "ой", s + "ой", s + "ой"), strict=True))
    s, end = adj[:-2], adj[-2:]
    if end == "ой":  # Заводской
        af = (adj, adj, s + "ому", s + "ого", s + "им", s + "ом")
    else:  # Кленовый
        af = (adj, adj, s + "ому", s + "ого", s + "ым", s + "ом")
    nf = _NOUN[words[1]]
    return {c: f"{a} {n}" for c, a, n in zip(CASES, af, nf, strict=True)}


