def _street_regex() -> list[tuple[re.Pattern, tuple[str, int]]]:
    out = []
    for key in [("V", i) for i in range(NX)] + [("H", j) for j in range(NY)]:
        forms = sorted(set(sforms(key).values()), key=len, reverse=True)
        out.append((re.compile(r"\b(" + "|".join(map(re.escape, forms)) + r")\b"), key))
    return out


def naive_last_corner(ws: Path) -> None:
    """Ключевые слова: последний явно названный угол, иначе две последние названные улицы."""
    rx = _street_regex()
    answers: dict[str, tuple[int, int] | None] = {}
    for p in sorted((ws / "notes").glob("n*.md")):
        text = p.read_text(encoding="utf-8")
        hits = sorted((m.start(), key) for r, key in rx for m in r.finditer(text))
        v = [k for _pos, k in hits if k[0] == "V"]
