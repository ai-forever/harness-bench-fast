def _judge_messages(item: dict, text: str) -> list[dict]:
    item["_head_ok"] = text.split("\n")[:_HEAD_LINES] == item["head"]
    item["_lost"] = sorted(set(item["distract"]) - _mentions(text))
    item["_added"] = sorted(_mentions(text) - set(item["named"]))
    return [{"role": "system", "content": _judge_system()}, {"role": "user", "content": text}]


def _judge_accept(item: dict, reply: str) -> tuple[bool, str]:
    if not item.get("_head_ok", True):
        return False, "первые шесть строк (шапка заметки) должны остаться дословно такими же, как в черновике"
    if item.get("_lost"):
        return False, ("пропали посторонние упоминания улиц (" + ", ".join(item["_lost"]) + "): верни эти реплики "
                       "про чужие или прошлые поездки, советы и истории, явно не про эту поездку")
    if item.get("_added"):
        return False, ("в тексте появились улицы, которых нет в черновике (" + ", ".join(item["_added"]) + "): не "
                       "называй новых улиц — ни в маршруте, ни в болтовне")
    got = _parse_reply(reply)
    if got is None:
        return False, "независимый читатель не смог восстановить маршрут по тексту"
    truth = item["canon"]
    k = _first_diff(truth, got, item["day"])
    pos = _run_canon(got, item["day"]) if all(None not in s.values() for s in got["steps"]) else None
    if k is None and pos == item["answer"]:
        return True, ""
    if k == 0:
        what = (f"старт: читатель понял склад «{got['depot']}», направление {_DIR_WORD.get(got['dir'], '?')}; должно "
                f"быть «{truth['depot']}», {_DIR_WORD[truth['dir']]}")
    elif k is not None and k > len(got["steps"]):
        what = f"читатель не нашёл шаг {k}: {_describe(truth['steps'][k - 1])}"
    elif k is not None and k > len(truth["steps"]):
        what = f"читатель нашёл лишний шаг {k}: {_describe(got['steps'][k - 1])}"
    elif k is not None:
        what = (f"шаг {k}: читатель понял «{_describe(got['steps'][k - 1])}», а должно быть "
                f"«{_describe(truth['steps'][k - 1])}»")
    else:
        what = "шаги совпали, но маршрут не исполняется"
    return False, f"независимый читатель по правилам восстановил маршрут иначе — {what}. Сделай это место однозначным"


