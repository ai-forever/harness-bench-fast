_STEP_KEYS = {"cross": ("n", "side"), "turn": ("n", "side"), "landmark": ("lm", "side"), "street": ("street", "side"),
              "blocks": ("n",), "uturn": (), "end": (), "cancelled": ("street", "side"), "stop_blocks": ("n",),
              "stop_landmark": ("lm",), "stop_street": ("street",), "stop_here": ()}


def _e(s: str) -> str:
    return s.replace("ё", "е").replace("Ё", "Е")


@functools.cache
def _street_words() -> dict[str, str]:
    """Первое слово любой падежной формы названия → название в им. падеже."""
    out = {}
    for key in [("V", i) for i in range(NX)] + [("H", j) for j in range(NY)]:
        for form in sforms(key).values():
            out[_e(form.split()[0]).casefold()] = sname(key)
    return out


def _n_street(v) -> str | None:
    words = re.findall(r"[а-яa-z-]+", _e(str(v)).casefold())
    words = [w_ for w_ in words if not w_.startswith(("улиц", "ул", "проспект", "просп", "бульвар", "переул"))]
    return _street_words().get(words[0]) if words else None


def _n_lm(v) -> str:
    s = _e(str(v)).casefold().replace("«", "").replace("»", "").replace('"', "").strip()
    if m := re.fullmatch(r"l\s*0?(\d{1,2})", s):
        return f"L{int(m.group(1)):02d}"
    for tp in LM_TYPES:
        if _e(tp) == s:
            return tp
    for lm in LANDMARKS:
        if _e(lm[2][0]).casefold().replace("«", "").replace("»", "") == s:
            return lm[0]
    return str(v)


def _n_side(v) -> str | None:
    s = str(v).strip().casefold()
    if s in ("r", "right") or s.startswith(("напр", "прав")):
        return "R"
    if s in ("l", "left") or s.startswith(("нал", "лев")):
        return "L"
    return None


def _n_dir(v) -> str | None:
    s = _e(str(v)).strip().casefold()
    for d_, words in {"N": ("n", "с", "север", "к бору"), "S": ("s", "ю", "юг", "к реке"),
                      "E": ("e", "в", "восток", "к полям"), "W": ("w", "з", "запад", "к железн")}.items():
        if s in words or s.startswith(words[2:]):
            return d_
    return None


def _n_int(v) -> int | None:
    s = _e(str(v)).strip().casefold()
    if m := re.search(r"\d+", s):
        return int(m.group(0))
    for stem, k in (("перв", 1), ("один", 1), ("втор", 2), ("два", 2), ("трет", 3), ("три", 3), ("четв", 4),
                    ("четыр", 4), ("пят", 5)):
        if s.startswith(stem):
            return k
    return None


def _n_val(field: str, v):
    return {"n": _n_int, "side": _n_side, "lm": _n_lm}[field](v)


def _n_step(raw: dict) -> dict:
    t = str(raw.get("t", "")).strip().casefold()
    if t == "stop_next":
        t, raw = "stop_blocks", dict(raw, n=1)
    out: dict = {"t": t}
    for k in _STEP_KEYS.get(t, ()):
        v = raw.get(k)
        out[k] = {"n": _n_int, "side": _n_side, "lm": _n_lm, "street": _n_street}[k](v)
    fx = raw.get("fix")
    if isinstance(fx, dict) and fx:
        field = {"ref": "lm"}.get(str(fx.get("field")), str(fx.get("field")))
        late = fx.get("late")
        out["fix"] = {"field": field, "was": _n_val(field, fx.get("was")) if field in ("n", "side", "lm") else None,
                      "late": late is True or str(late).casefold() == "true"}
    return out


def _parse_reply(reply: str) -> dict | None:
    match = re.search(r"\{.*\}", reply, re.S)
    try:
        got = json.loads(match.group(0)) if match else None
    except json.JSONDecodeError:
        return None
    if not isinstance(got, dict) or not isinstance(got.get("steps"), list):
        return None
    dep = _e(str(got.get("depot", ""))).casefold()
    depot = next((name for name, _x, _y in DEPOTS if _e(name).casefold() in dep), None)
    steps = [_n_step(s) for s in got["steps"] if isinstance(s, dict)]
    return {"depot": depot, "dir": _n_dir(got.get("dir", "")), "steps": _fold(steps)}


def _first_diff(truth: dict, got: dict, day: date) -> int | None:
    """Номер первого расходящегося шага (0 — старт); None — списки совпадают.

    «На n-м перекрёстке» и «n-й поворот» с теми же n и стороной взаимозаменяемы там, где дают одно и то
    же место: ловушка счёта поворотов этим не теряется.
    """
    if (got["depot"], got["dir"]) != (truth["depot"], truth["dir"]):
        return 0
    _n, x, y = next(d_ for d_ in DEPOTS if d_[0] == truth["depot"])
    w = Walker(x, y, truth["dir"], day, frozenset())
    for i, (a, b) in enumerate(zip(truth["steps"], got["steps"], strict=False), 1):
        if a != b:
            same_rest = {k: v for k, v in a.items() if k != "t"} == {k: v for k, v in b.items() if k != "t"}
            if not ({a["t"], b["t"]} == {"cross", "turn"} and same_rest
                    and _step_alt(w, _internal(a), frozenset()) == _step_alt(w, _internal(b), frozenset())):
                return i
        w.run_step(_internal(a))
    if len(truth["steps"]) != len(got["steps"]):
        return min(len(truth["steps"]), len(got["steps"])) + 1
    return None


