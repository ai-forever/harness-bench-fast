def setup(ws: Path) -> None:
    reviews = build()
    write(ws, "guidelines.md", GUIDELINES)
    for b in range(N_BATCHES):
        chunk = reviews[b * PER_BATCH:(b + 1) * PER_BATCH]
        body = "".join(json.dumps(_public(r), ensure_ascii=False) + "\n" for r in chunk)
        write(ws, f"reviews/batch_{b + 1:02d}.jsonl", body)


def _write_labels(ws: Path, labels: dict[str, dict[str, str]]) -> None:
    body = "".join(
        json.dumps({"id": rid, "labels": lab}, ensure_ascii=False) + "\n" for rid, lab in labels.items()
    )
    write(ws, "labels.jsonl", body)


def gold(ws: Path) -> None:
    _write_labels(ws, {r["id"]: r["_labels"] for r in build()})


def check(ws: Path) -> str:
    rows = read_jsonl(ws, "labels.jsonl")
    got: dict[str, dict[str, str]] = {}
    for n, row in enumerate(rows, 1):
        assert isinstance(row, dict) and "id" in row and "labels" in row, (
            f"labels.jsonl:{n}: нужны поля id и labels"
        )
        lab = row["labels"]
        assert isinstance(lab, dict), f"labels.jsonl:{n}: labels должен быть объектом"
        clean: dict[str, str] = {}
        for k, v in lab.items():
            key = str(k).strip().casefold()
            val = str(v).strip().casefold()
            assert key in ASPECTS, f"labels.jsonl:{n}: неизвестный аспект {k!r}"
            assert val in LABELS, f"labels.jsonl:{n}: недопустимая метка {v!r}"
            clean[key] = val
        got[str(row["id"]).strip()] = clean
    reviews = build()
    correct = 0
    errors = []
    for r in reviews:
        if got.get(r["id"]) == r["_labels"]:
            correct += 1
        elif len(errors) < 5:
            errors.append(r["id"] + (" отсутствует" if r["id"] not in got else " размечен неверно"))
    return require_share(len(reviews), correct, min_share=MIN_SHARE, what="отзывы", errors=errors)


