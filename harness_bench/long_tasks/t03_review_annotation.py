_GIDX = {"m": 0, "f": 1, "n": 2, "pl": 3}
_FIDX = {"m": 0, "f": 1, "pl": 2}
_PH = re.compile(r"\{([^{}]*)\}")


class Ctx:
    def __init__(self, R: random.Random, female: bool, product: tuple, friend: tuple) -> None:
        self.R = R
        self.female = female
        self.product = product
        self.friend = friend

    def fill(self, tpl: str) -> str:
        R = self.R
        p = self.product
        fr = self.friend

        def rep(m: re.Match) -> str:
            key = m.group(1)
            if key.startswith("g:"):
                return key[2:].split("|")[1 if self.female else 0]
            if key.startswith("p:"):
                return key[2:].split("|")[_GIDX[p[4]]]
            if key.startswith("f:"):
                return key[2:].split("|")[_FIDX[fr[3]]]
            if key == "P":
                return p[0]
            if key == "Pc":
                return p[0][0].upper() + p[0][1:]
            if key == "Pa":
                return p[1]
            if key == "Pg":
                return p[2]
            if key == "Pi":
                return p[3]
            if key == "F":
                return fr[0]
            if key == "Fc":
                return fr[0][0].upper() + fr[0][1:]
            if key == "Fg":
                return fr[1]
            if key == "Fd":
                return fr[2]
            if key == "DAYS":
                n = R.randint(5, 14)
                return f"{n} {_plural(n, 'день', 'дня', 'дней')}"
            if key == "DAYS2":
                return R.choice(["два дня", "три дня", "сутки"])
            if key == "HOURS":
                n = R.randint(2, 5)
                return f"{n} {_plural(n, 'час', 'часа', 'часов')}"
            if key == "WEEKS":
                return R.choice(WEEKS)
            if key == "SUM":
                return _rub(R.choice(SUMS))
            if key == "BIGSUM":
                n = R.choice(BIGSUMS)
                return f"{n} {_plural(n, 'тысячу', 'тысячи', 'тысяч')} рублей"
            if key == "PCT":
                return f"скидку {R.choice([10, 15, 20, 25])} %"
            if key == "STORE":
                return R.choice(STORES)
            if key == "TIME":
                return R.choice(TIMES_GEN)
            if key == "CDAT":
                return R.choice(COURIERS_DAT)
            raise KeyError(key)

        return _PH.sub(rep, tpl)


def _lower_first(s: str) -> str:
    return s[0].lower() + s[1:] if s and s[0].isupper() and not s[1:2].isupper() else s


