def _naive_labels(text: str) -> dict[str, str]:
    found: dict[str, set[str]] = {}
    for sent in re.split(r"(?<=[.!?])\s+|\n+", text.lower()):
        aspects = [a for a, keys in _NAIVE_ASPECT.items() if any(k in sent for k in keys)]
        if not aspects:
            continue
        score = 0
        for word_list, sign in ((_NAIVE_POS, 1), (_NAIVE_NEG, -1)):
            for w in word_list:
                for m in re.finditer(re.escape(w), sent):
                    before = sent[max(0, m.start() - 8):m.start()]
                    s = -sign if re.search(r"\bне\s+(\w+\s+)?$", before) else sign
                    score += s
        if score == 0:
            continue
        pol = "pos" if score > 0 else "neg"
        for a in aspects:
            found.setdefault(a, set()).add(pol)
    return {a: ("mixed" if len(p) > 1 else next(iter(p))) for a, p in found.items()}


def naive_keyword_labels(ws: Path) -> None:
    """Разметка по словарям ключевых слов с учётом «не» — без правил инструкции."""
    _write_labels(ws, {r["id"]: _naive_labels(r["text"]) for r in build()})


