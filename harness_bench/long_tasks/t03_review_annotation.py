def _plural(n: int, one: str, few: str, many: str) -> str:
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many


def _rub(n: int) -> str:
    text = f"{n:,}".replace(",", " ")
    return f"{text} {_plural(n, 'рубль', 'рубля', 'рублей')}"


