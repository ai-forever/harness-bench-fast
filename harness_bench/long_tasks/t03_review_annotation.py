def _judge_messages(item: dict, text: str) -> list[dict]:
    return [
        {
            "role": "system",
            "content": GUIDELINES
            + "\n\nРазметь один отзыв по этой инструкции. Ответь только JSON-объектом вида "
            '{"labels": {"delivery": "neg"}} — только оценённые аспекты.',
        },
        {"role": "user", "content": text},
    ]


def _judge_accept(item: dict, reply: str) -> tuple[bool, str]:
    match = re.search(r"\{.*\}", reply, re.S)
    try:
        got = json.loads(match.group(0)).get("labels", {}) if match else None
    except (json.JSONDecodeError, AttributeError):
        got = None
    if not isinstance(got, dict):
        return False, "независимый разметчик не смог разметить текст"
    got = {str(k).strip(): str(v).strip() for k, v in got.items()}
    if got == item["labels"]:
        return True, ""
    return False, (
        f"независимый разметчик по инструкции получил {json.dumps(got, ensure_ascii=False)}, "
        f"а должно быть {json.dumps(item['labels'], ensure_ascii=False)}: сделай роли фрагментов "
        "однозначнее, сохранив разметку"
    )


