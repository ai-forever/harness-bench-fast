GUIDELINES = """\
# Инструкция по разметке отзывов «Ампер»

Версия 3.2. Документ для асессоров. Прочитайте его целиком до начала работы:
в конце собраны разборы типичных ошибок прошлых разметчиков.

## 1. Что размечаем

Каждый отзыв — свободный текст покупателя интернет-магазина электроники «Ампер».
Для каждого из пяти **аспектов** нужно решить, оценил ли его **автор отзыва**
применительно к **этому магазину и этой покупке**, и если да — с какой тональностью.

| Код | Аспект | Что сюда относится |
|---|---|---|
| `price` | Цена | цена товара, ценник, стоимость, скидки, акции, промокоды, бонусы и кешбэк, скрытые доплаты, наценки, **стоимость доставки** |
| `delivery` | Доставка | сроки и скорость доставки, курьер и его поведение, звонки и уведомления о доставке, трекинг, интервалы, пункт выдачи и его сотрудники |
| `quality` | Качество товара | сам купленный товар: сборка, материалы, работа, поломки, брак, надёжность |
| `support` | Поддержка | общение с сотрудниками магазина вне доставки: горячая линия, чат, операторы, менеджеры, консультанты, оформление возврата и обмена, гарантийные обращения в магазин |
| `packaging` | Упаковка | коробка и её состояние, защитный наполнитель (пупырка, уплотнитель, пенопласт), заводская плёнка на коробке, пакеты, подарочная упаковка, количество упаковочного мусора |

Аспект определяется **по смыслу**, а не по слову:

* «Стоимость доставки», «за доставку взяли …», «доставка платная и дорогая» — это
  `price`, а не `delivery`: оценивается цена, а не то, как везли.
* «Качество упаковки» — `packaging`; «качество обслуживания в чате / по телефону» —
  `support`. `quality` — только качество самого товара.
* Курьер, водитель, сотрудник пункта выдачи — `delivery`, даже если речь об их вежливости.
  Оператор горячей линии, менеджер, консультант чата — `support`.
* Слова в переносном значении аспект не называют: «подарок доставил массу радости»,
  «спасибо мужу за моральную поддержку», «для дорогой мамы ничего не жалко» — это не
  `delivery`, не `support` и не `price`.

## 2. Метки

Для каждого **оценённого** аспекта ставится одна метка:

* `pos` — все учитываемые оценки аспекта положительные;
* `neg` — все учитываемые оценки аспекта отрицательные;
* `mixed` — среди учитываемых оценок аспекта есть и положительные, и отрицательные
  (например, «курьер приехал вовремя, но нахамил» — `delivery: mixed`).

Если аспект не оценён, его **не указывают** вовсе (никаких `none`, `neutral`, пустых
строк). Отзыв, в котором не оценён ни один аспект, получает пустой набор меток.

Две положительные оценки одного аспекта — это `pos`, а не `mixed`. Сколько раз
упомянут аспект, значения не имеет.

## 3. Что считается оценкой

Оценка — это высказанное **самим автором** суждение о том, хорош или плох аспект
**в этом магазине** в **текущем** (для автора) состоянии: «курьер опоздал на три часа»,
«цена приятная», «коробка мятая», «в чате ответили за минуту». Оценка может быть
выражена фактом, если факт однозначно хороший или плохой («ждал девять дней» — плохо,
«привезли на следующий день» — хорошо).

### 3.1. Отрицание

Отрицание меняет тональность: «курьер не опоздал ни на минуту» — `pos`; «цена не
кусается» — `pos`; «поддержка так и не помогла» — `neg`; «не назову доставку быстрой»,
«не сказал бы, что собрано качественно» — `neg`.

### 3.2. Сарказм

Сарказм — похвала, которая по смыслу описывает плохой опыт: «доставка просто
молниеносная — каких-то девять дней», «упаковка гениальная: всё в одном пакете»,
«отдельное спасибо курьеру, который оставил заказ под дождём». Часто его выдают
кавычки («выгодная» акция, «надёжная» упаковка), «ага», «ну конечно», «браво»,
«шедевр», «так держать», но главный признак — противоречие между хвалебными словами
и описанным фактом. **Сарказм инвертирует тональность: такая оценка — `neg`.**

### 3.3. Время: раньше и теперь

Если автор противопоставляет прошлое состояние аспекта текущему («раньше
доставку ждали неделю, а теперь привезли за день», «когда-то цены радовали, а сейчас
выросли», «первые дни подвисал, но после обновления работает идеально»), учитывается
**только текущее** состояние. Прошлая половина такого противопоставления оценкой не
считается. Маркеры прошлого: «раньше», «когда-то», «в прошлые разы», «в прошлый раз»,
«года два назад», «первое время», «поначалу». Маркеры текущего: «теперь», «сейчас»,
«в этот раз», «после обновления».

### 3.4. Дополнения к отзыву (UPD)

Иногда автор дописывает отзыв позже. Дополнение начинается с новой строки и с одной
из пометок: `UPD:`, `Upd.`, `Дополнение:`, `Обновляю отзыв:`, `UPD спустя неделю:`.

* Если в дополнении оценён аспект, который оценивался и в основном тексте, то для
  этого аспекта учитывается **только дополнение**; оценки из основного текста для
  него отбрасываются (не получается `mixed` из «до» и «после»).
* Аспекты, которых дополнение не касается, размечаются по основному тексту.
* Аспект, впервые оценённый в дополнении, размечается по дополнению.

### 3.5. Чужое мнение

Учитывается только мнение и опыт **автора**. Не являются оценкой: слова друзей,
родственников, коллег («брат говорит, что курьеры у них вечно опаздывают»), пересказ
чужих отзывов и форумов («в отзывах пишут…», «говорят, что…»), опыт других людей
(«сестре прислали заказ в рваном пакете») — даже если автор это не опровергает.

**Исключение:** если автор прямо присоединяется к чужому мнению как к своему опыту
(«…— и я с этим полностью согласен», «…— могу подтвердить: у меня было так же»,
«…— подтверждаю на собственном опыте», «…— и это чистая правда, я убедился сам»), это
уже оценка автора с той же тональностью.

### 3.6. Другие магазины и сравнения

Оцениваем только этот магазин. Не учитываются:

* высказывания о других магазинах и о товарах, купленных там («в «Техносфере» мне
  везли заказ месяц», «прошлый ноутбук из «Схемы» сломался через месяц»);
* **любые сравнения с другими магазинами**, в какую бы сторону они ни были: «здесь
  дешевле, чем в «Мегаватте»», «по сравнению с «Пикселем» курьеры тут быстрее», «в
  отличие от «ГигаДома», здесь не жалеют пупырки», «упаковывают хуже, чем в …». Даже
  если из сравнения можно вывести, хорошо или плохо здесь, метку по нему **не ставим**:
  сравнение говорит о соотношении магазинов, а не даёт самостоятельной оценки.

Сравнение с ожиданиями автора — не сравнение с магазином: «цена на 900 рублей ниже,
чем я рассчитывал» — обычная оценка `price: pos`.

### 3.7. Вопросы

Вопрос, которым автор что-то уточняет или спрашивает у читателей («а доставка в
пригород бесплатная?», «кто знает, в какие часы работает горячая линия?»), оценкой
не является.

### 3.8. Условное, пожелания, надежды

Не являются оценкой конструкции «если бы…», «будь…», «хотелось бы…», «было бы
здорово / неплохо, если бы…», «надеюсь…», — **даже если из них можно вывести
недовольство**. «Если бы курьер позвонил заранее, было бы идеально» не даёт
`delivery: neg`; «надеюсь, в следующий раз упакуют получше» не даёт `packaging: neg`.

### 3.9. Нейтральные упоминания

Упоминание аспекта без оценки меток не даёт: «доставку выбрал курьерскую»,
«коробку сохранил на случай ремонта», «платил картой при получении», «курьер приехал
около семи вечера», «в поддержку писал, только чтобы поменять адрес».

### 3.10. Общая оценка

Итоговые фразы без указания аспекта — «в целом доволен», «рекомендую магазин», «больше
заказывать не буду», «ставлю четыре звезды» — меток не дают. Звёзды и общий тон
отзыва на метки аспектов не влияют.

## 4. Порядок работы с отзывом

1. Разбейте отзыв на высказывания; отделите дополнение (UPD), если оно есть.
2. Для каждого высказывания определите аспект по смыслу (раздел 1).
3. Отбросьте то, что не является оценкой автора об этом магазине в текущем
   состоянии: чужое мнение без присоединения, другие магазины и сравнения, вопросы,
   условное и пожелания, нейтральные факты, прошлую половину «раньше/теперь».
4. Для оставшихся оценок определите тональность с учётом отрицания и сарказма.
5. Примените правило дополнения и соберите метки: только `pos`, только `neg` или обе
   (`mixed`).

## 5. Формат результата

Файл `labels.jsonl`, по одной строке на каждый отзыв из всех пакетов:

```
{"id": "r0001", "labels": {"delivery": "neg", "price": "pos"}}
{"id": "r0002", "labels": {}}
```

Ключи — только коды из таблицы раздела 1, значения — только `pos`, `neg`, `mixed`.

## 6. Разборы

**Пример 1.** «Курьер позвонил заранее и донёс заказ до квартиры. Сестра говорит, что
поддержка у них хамит. Стоимость доставки — 600 рублей, многовато.»
→ `{"delivery": "pos", "price": "neg"}`. Мнение сестры не учитывается; стоимость
доставки — это `price`.

**Пример 2.** «Цена просто подарок: всего-то половина моей зарплаты за обычный
чайник. Браво.» → `{"price": "neg"}` (сарказм: хвалебные слова, плохой факт).

**Пример 3.** «Раньше их чат молчал сутками, а теперь отвечают за минуту. Надеюсь, и
с возвратом всё будет так же быстро.» → `{"support": "pos"}`. Прошлое не
учитывается, надежда — тоже.

**Пример 4.** «Здесь привозят быстрее, чем в «Электроне». Коробка была белая.» → `{}`.
Сравнение и нейтральное упоминание.

**Пример 5.** «Телевизор радует картинкой, но пульт люфтит. Кстати, гарантия год или
два?» → `{"quality": "mixed"}`.

**Пример 6.** «Поддержка не отвечает третий день. UPD: перезвонили и всё решили за
десять минут.» → `{"support": "pos"}`. Дополнение заменяет оценку из основного текста.

**Пример 7.** «Друзья уверяют, что упаковывают тут на совесть, — подтверждаю на
собственном опыте. Если бы ещё скотча было поменьше…» → `{"packaging": "pos"}`.
Автор присоединился к мнению друзей; условная фраза не учитывается.

**Пример 8.** «Качество обслуживания в чате ужасное: ответили через сутки. Сам
чайник кипятит быстро.» → `{"support": "neg", "quality": "pos"}`.

**Пример 9.** «Для дорогой бабушки брали. Подарок доставил ей море радости. В целом
всё супер!» → `{}`. Переносные значения и общая оценка.

**Пример 10.** «Не скажу, что упаковка плохая: коробка целая, всё в пупырке. А вот
курьер не удосужился даже позвонить.» → `{"packaging": "pos", "delivery": "neg"}`.

## 7. Частые ошибки прошлых разметчиков

* Ставили `mixed` из-за чужого мнения или сравнения с другим магазином, которые
  расходились с мнением автора. Их просто не учитываем.
* Ставили `mixed`, когда в UPD автор изменил мнение. Правильно — метка по дополнению.
* Ставили `pos` за саркастическую похвалу.
* Относили стоимость доставки к `delivery`, а качество упаковки — к `quality`.
* Ставили `neg` за фразы «хотелось бы…» и «если бы…».
* Ставили метки за «рекомендую», «в целом доволен» и за звёзды.
* Пропускали отзывы: в `labels.jsonl` должна быть строка для каждого отзыва.
"""


