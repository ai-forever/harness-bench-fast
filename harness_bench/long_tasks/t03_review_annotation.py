def _rewrite_items() -> list[dict]:
    items = []
    for r in build():
        lines = []
        for c in r["_clauses"]:
            verdict = f"учитывается как {c['aspect']}={c['counted']}" if c["counted"] else "не учитывается"
            lines.append(f"- «{c['text']}» — {_ROLE.get(c['kind'], c['kind'])}; {verdict}")
        labels = json.dumps(r["_labels"], ensure_ascii=False)
        brief = (
            f"Автор: {r['author']} (пол по имени), товар: {r['product']}.\n"
            f"Правильная разметка всего отзыва по инструкции: {labels}.\n"
            "Смысловые фрагменты черновика и их роль:\n" + "\n".join(lines)
        )
        items.append({"key": r["id"], "draft": r["text"], "brief": brief, "labels": r["_labels"]})
    return items


