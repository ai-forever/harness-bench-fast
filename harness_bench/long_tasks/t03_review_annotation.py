def _retag() -> None:
    for key, items in B.items():
        new = []
        for facet, tpl in items:
            for prefix, tags in RETAG.items():
                if tpl.startswith(prefix):
                    facet = tags
                    break
            new.append((facet, tpl))
        B[key] = new


