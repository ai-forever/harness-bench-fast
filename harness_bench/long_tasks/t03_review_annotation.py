#   counted: 'pos'/'neg' — учитываемая по правилам полярность, None — не учитывается
#   surface: полярность «по словам» (для ближних промахов)
#   seg: 'main' | 'upd'


def _labels_from(clauses: list[dict], *, mode: str = "gold") -> dict[str, str]:
    """Метки по правилам (mode='gold') или по намеренно неверным правилам."""
    main: dict[str, list[str]] = {}
    upd: dict[str, list[str]] = {}
    for c in clauses:
        pol = c["counted"]
        if mode == "no_sarcasm" and c["kind"] == "sarc":
            pol = "pos"
        if mode == "count_foreign" and c["kind"] in ("other", "compare", "friend") and c["surface"]:
            pol = c["surface"]
        aspect = c["aspect"]
        if mode == "cross_word" and c["kind"] == "cross":
            aspect = {"price": "delivery"}.get(aspect, "quality")
        if mode == "count_hypo" and c["kind"] == "cond":
            pol = c["surface"]
        if mode == "count_past" and c["kind"] == "past":
            (upd if c["seg"] == "upd" else main).setdefault(c["aspect"], []).append(c["old"])
        if pol is None:
            continue
        seg = c["seg"]
        if mode == "no_upd":
            seg = "main"
        (upd if seg == "upd" else main).setdefault(aspect, []).append(pol)
    out: dict[str, str] = {}
    for a in ASPECTS:
        pols = upd.get(a) or main.get(a)
        if not pols:
            continue
        s = set(pols)
        out[a] = "mixed" if len(s) > 1 else pols[0]
    return out


def _tags(facet: str) -> set[str]:
    return set(facet.split("+")) if facet else set()


def _pick(R: random.Random, kind: str, aspect: str, pol: str, used: set[str],
          extra: list[tuple[str, str]] = ()) -> tuple[str, str]:
    pool = list(B.get((kind, aspect, pol), [])) + list(extra)
    options = [x for x in pool if not (_tags(x[0]) & used)]
    if not options:
        return ("", "")
    return R.choice(options)


def _make_review(R: random.Random, idx: int) -> dict:
    female = R.random() < 0.5
    first = R.choice(AUTHORS_F if female else AUTHORS_M)
    author = f"{first} {R.choice(SURNAME_INITIALS)}."
    product = R.choice(PRODUCTS)
    friend = R.choice(FRIENDS)
    ctx = Ctx(R, female, product, friend)

    n_eval = R.choices([0, 1, 2, 3, 4], weights=[3, 14, 33, 35, 15])[0]
    evaluated = R.sample(ASPECTS, n_eval)
    target = {a: R.choices(LABELS, weights=[44, 40, 16])[0] for a in evaluated}
    upd_aspect = R.choice(evaluated) if evaluated and R.random() < 0.17 else None
    if upd_aspect and target[upd_aspect] == "mixed":
        target[upd_aspect] = R.choice(["pos", "neg"])

    body: list[dict] = []  # основной текст
    upd_items: list[dict] = []
    used_facets: dict[str, set[str]] = {a: set() for a in ASPECTS}

    frames_used: set[str] = set()

    def take_frame(frames: list[str]) -> str:
        free = [f for f in frames if f not in frames_used] or frames
        frame = R.choice(free)
        frames_used.add(frame)
        return frame

    def counted_clause(aspect: str, pol: str, seg: str) -> dict:
        used = used_facets[aspect]
        if seg == "upd":
            _, tpl = _pick(R, "upd", aspect, pol, set())
            return dict(aspect=aspect, kind="upd", surface=pol, counted=pol, seg="upd", text=ctx.fill(tpl))
        kinds = ["direct"] * 50 + ["past"] * 13 + ["agree"] * 6
        if pol == "neg":
            kinds += ["sarc"] * 22
        if (("cross", aspect, pol)) in B:
            kinds += ["cross"] * 14
        for _ in range(20):
            kind = R.choice(kinds)
            if kind == "agree":
                facet, emb = _pick(R, "emb", aspect, pol, used)
                if not emb:
                    continue
                used |= _tags(facet)
                frame = take_frame(FRIEND_FRAMES if "{Fd}" in emb or R.random() < 0.6 else IMPERSONAL_FRAMES)
                text = ctx.fill(frame.replace("{emb}", emb)).rstrip(".") + ctx.fill(R.choice(AGREE_TAILS))
                return dict(aspect=aspect, kind="agree", surface=pol, counted=pol, seg=seg, text=text)
            extra = []
            if kind == "direct" and aspect == "quality":
                extra = [("spec", t) for t in product[5 if pol == "pos" else 6]]
            facet, tpl = _pick(R, kind, aspect, pol, used, extra)
            if not tpl:
                continue
            used |= _tags(facet)
            if kind == "past":
                return dict(aspect=aspect, kind="past", surface=pol, counted=pol, seg=seg,
                            text=ctx.fill(tpl), old=("neg" if pol == "pos" else "pos"))
            surface = "pos" if kind == "sarc" else pol
            return dict(aspect=aspect, kind=kind, surface=surface, counted=pol, seg=seg, text=ctx.fill(tpl))
        raise RuntimeError("не удалось подобрать клаузу")

    groups: list[list[dict]] = []
    for a in evaluated:
        lab = target[a]
        if a == upd_aspect:
            upd_items.append(counted_clause(a, lab, "upd"))
            if R.random() < 0.85:
                before = "neg" if lab == "pos" else "pos"
                groups.append([counted_clause(a, before, "main")])
            continue
        if lab == "mixed":
            for _attempt in range(30):
                saved = set(used_facets[a])
                try:
                    pair = [counted_clause(a, "pos", "main"), counted_clause(a, "neg", "main")]
                    break
                except RuntimeError:
                    used_facets[a] = saved
            else:
                raise RuntimeError("не удалось собрать mixed")
            R.shuffle(pair)
            groups.append(pair)
        else:
            grp = [counted_clause(a, lab, "main")]
            if R.random() < 0.22:
                with contextlib.suppress(RuntimeError):
                    grp.append(counted_clause(a, lab, "main"))
            groups.append(grp)

    # ловушки
    n_traps = R.choices([1, 2, 3], weights=[22, 45, 33])[0]
    unevaluated = [a for a in ASPECTS if a not in evaluated]
    for _ in range(n_traps):
        kind = R.choices(["other", "compare", "friend", "question", "cond", "neutral"],
                         weights=[16, 18, 22, 12, 16, 16])[0]
        a = R.choice(unevaluated) if unevaluated and R.random() < 0.65 else R.choice(ASPECTS)
        final = target.get(a)
        if kind in ("other", "compare", "friend"):
            if final in ("pos", "neg"):
                spol = "neg" if final == "pos" else "pos"
            else:
                spol = R.choice(["pos", "neg"])
            if kind == "friend":
                _, emb = _pick(R, "emb", a, spol, set())
                frames = FRIEND_FRAMES if "{Fd}" in emb else FRIEND_FRAMES + IMPERSONAL_FRAMES
                text = ctx.fill(take_frame(frames).replace("{emb}", emb))
            else:
                _, tpl = _pick(R, kind, a, spol, set())
                text = ctx.fill(tpl)
            body.append(dict(aspect=a, kind=kind, surface=spol, counted=None, seg="main", text=text))
        else:
            facet, tpl = _pick(R, kind, a, "", used_facets[a])
            if not tpl:
                continue
            used_facets[a] |= _tags(facet)
            surface = "neg" if kind == "cond" else None
            body.append(dict(aspect=a, kind=kind, surface=surface, counted=None, seg="main", text=ctx.fill(tpl)))

    # сборка основного текста: единицы (текст, клаузы, тип)
    units: list[tuple[str, list[dict], str]] = []
    for grp in groups:
        if len(grp) == 2 and grp[0]["text"].endswith(".") and R.random() < 0.5 \
                and grp[0]["kind"] == grp[1]["kind"] == "direct" \
                and grp[0]["counted"] != grp[1]["counted"]:
            joiner = R.choice([", но ", ", а вот ", ", однако "])
            units.append((grp[0]["text"][:-1] + joiner + _lower_first(grp[1]["text"]), grp, "eval"))
        else:
            units.extend((c["text"], [c], "eval") for c in grp)
    units.extend((c["text"], [c], "trap") for c in body)
    units = [(_upper_first(t), cl, k) for t, cl, k in units]
    R.shuffle(units)
    for f in R.sample(FILLERS, R.choice([1, 1, 2, 2, 3])):
        units.insert(R.randint(0, len(units)), (_upper_first(ctx.fill(f)), [], "filler"))
    intro = ctx.fill(R.choice(INTROS))
    closing = ctx.fill(R.choice(CLOSINGS)) if R.random() < 0.7 else ""
    upd_text = ""
    if upd_items:
        upd_text = "\n\n" + R.choice(UPD_MARKERS) + " " + " ".join(_upper_first(c["text"]) for c in upd_items)

    def render() -> str:
        parts = [intro] + [u[0] for u in units] + ([closing] if closing else [])
        return " ".join(parts) + upd_text

    text = render()
    # слишком длинные отзывы укорачиваем за счёт «воды» и лишних ловушек
    while len(text) > 940:
        fill_idx = [i for i, u in enumerate(units) if u[2] == "filler"]
        trap_idx = [i for i, u in enumerate(units) if u[2] == "trap"]
        if fill_idx:
            units.pop(fill_idx[-1])
        elif closing:
            closing = ""
        elif len(trap_idx) > 1:
            units.pop(trap_idx[-1])
        else:
            break
        text = render()
    while len(text) < 320:
        units.insert(0, (_upper_first(ctx.fill(R.choice(FILLERS))), [], "filler"))
        text = render()
    clauses = [c for u in units for c in u[1]] + upd_items
    labels = _labels_from(clauses)
    day = R.randint(1, 28)
    month = R.randint(1, 12)
    year = R.choice([2025, 2026]) if month <= 8 else 2025
    return dict(
        id=f"r{idx:04d}",
        author=author,
        date=f"{year}-{month:02d}-{day:02d}",
        product=product[0],
        text=text,
        _clauses=clauses,
        _labels=labels,
    )


def _upper_first(s: str) -> str:
    return s[0].upper() + s[1:] if s else s


@functools.cache
def build() -> list[dict]:
    R = rng(TASK_ID)
    return [_make_review(R, i + 1) for i in range(N_BATCHES * PER_BATCH)]


