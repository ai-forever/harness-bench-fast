def aliases(c: dict, *, patr_ok: bool = True) -> list[tuple[dict[str, str], float]]:
    """Способы назвать персонажа (падежные формы, вес)."""
    g = c["g"]
    old = c["born"] < 1965
    out = [(decl(c["first"], g), 0.6 if old else 2.0),
           (decl(c["sur"], g, "surname"), 1.2)]
    for i, nick in enumerate(c["nick"]):
        out.append((decl(nick, g), (2.5 if i == 0 else 0.6)))
    if patr_ok:
        out.append((decl_phrase([(c["first"], "name"), (c["patr"], "patr")], g), 3.0 if old else 0.3))
    return out


