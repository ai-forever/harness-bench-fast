_SLOT = re.compile(r"\{([^{}]+)\}")
_CTX = {"mood": "hot", "tod": "day"}  # погода главы и время суток абзаца (ставит render_world)
_WEATHER = {"hot", "rain"}
_TOD = {"morn", "day", "eve"}


def tags_ok(tags: str, mood: str, tod: str) -> bool:
    for t in filter(None, tags.split(",")):
        if (t in _WEATHER and t != mood) or (t in _TOD and t != tod):
            return False
    return True


class Para:
    """Один абзац: следит за тем, кто уже назван и можно ли использовать местоимения."""

    def __init__(self, R: random.Random, T: dict | None, P: dict | None, *, patr_ok: bool = True):
        self.R = R
        self.roles = {"T": T, "P": P}
        self.seen: set[str] = set()
        self.pron_ok = True
        self.alias = {}
        for role, c in self.roles.items():
            if c is not None:
                al = aliases(c, patr_ok=patr_ok if role == "T" else True)
                self.alias[role] = al
        self.cur_alias: dict[str, dict[str, str]] = {}
        self.sentences: list[str] = []
        self.used: set[str] = set()
        self.cur: set[str] = set()
        self.mood = _CTX["mood"]
        self.tod = _CTX["tod"]

    def _name(self, role: str, case: str) -> str:
        if role not in self.cur_alias or self.R.random() < 0.15:
            forms, weights = zip(*self.alias[role], strict=True)
            self.cur_alias[role] = self.R.choices(forms, weights)[0]
        key = case[1:] if len(case) == 2 and case.startswith("n") else case
        return self.cur_alias[role][key]

    def _ref(self, role: str, case: str) -> str:
        c = self.roles[role]
        assert c is not None, role
        g = 0 if c["g"] == "m" else 1
        if case == "pos":
            assert role in self.seen, "possessive before name"
            return _PRON["pos"][g]
        if case == "nn":
            self.seen.add(role)
            self.cur.add(role)
            return self._name(role, "n")
        pron_possible = case != "g"
        chance = 1.0 if role in self.cur else 0.62
        use_pron = pron_possible and role in self.seen and self.pron_ok and self.R.random() < chance
        self.seen.add(role)
        self.cur.add(role)
        if use_pron:
            return _PRON[case][g]
        return self._name(role, case)

    def render(self, tpl: str, vals: dict[str, str] | None = None) -> str:
        vals = vals or {}
        self.used.add(tpl)
        self.cur = set()
        extra = tpl.startswith("!")
        tpl = tpl.lstrip("!")

        def sub(m: re.Match) -> str:
            body = m.group(1)
            if body.startswith("v."):
                return vals[body[2:]]
            if ":" in body:
                role, opts = body.split(":", 1)
                a, b = opts.split("|", 1)
                gender = vals["_" + role] if role in ("S", "A", "W") else self.roles[role]["g"]  # type: ignore[index]
                return a if gender == "m" else b
            role, _, case = body.partition(".")
            return self._ref(role, case or "n")

        text = cap(_SLOT.sub(sub, tpl))
        if text[-1] not in ".!?»…":
            text += "."
        if extra:
            self.pron_ok = False
        self.sentences.append(text)
        return text

    def text(self) -> str:
        return " ".join(self.sentences)


def split_tag(tpl: str) -> tuple[str, str]:
    body, _, tag = tpl.partition("@")
    return body, tag


