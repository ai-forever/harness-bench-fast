_VELAR_HUSH = set("гкхжшщч")
_HUSH = set("жшщчц")
CASES = ("n", "g", "d", "a", "i", "p")


def decl(word: str, gender: str = "m", kind: str = "name") -> dict[str, str]:
    """Падежные формы одушевлённого имени/клички/фамилии (n g d a i p)."""
    w = word
    if kind == "indecl":
        forms = (w,) * 6
    elif kind == "surname":
        if gender == "m":
            forms = (w, w + "а", w + "у", w + "а", w + "ым", w + "е")
        else:
            s = w[:-1]
            forms = (w, s + "ой", s + "ой", s + "у", s + "ой", s + "ой")
    elif kind == "patr":
        if gender == "m":
            forms = (w, w + "а", w + "у", w + "а", w + "ем", w + "е")
        else:
            s = w[:-1]
            forms = (w, s + "ы", s + "е", s + "у", s + "ой", s + "е")
    elif w.endswith("ия"):
        s = w[:-1]
        forms = (w, s + "и", s + "и", s + "ю", s + "ей", s + "и")
    elif w.endswith("я"):
        s = w[:-1]
        forms = (w, s + "и", s + "е", s + "ю", s + "ей", s + "е")
    elif w.endswith("а"):
        s = w[:-1]
        forms = (w, s + ("и" if s[-1] in _VELAR_HUSH else "ы"), s + "е", s + "у",
                 s + ("ей" if s[-1] in _HUSH else "ой"), s + "е")
    elif w.endswith("ий"):
        s = w[:-1]
        forms = (w, s + "я", s + "ю", s + "я", s + "ем", s + "и")
    elif w.endswith(("й", "ь")):
        s = w[:-1]
        forms = (w, s + "я", s + "ю", s + "я", s + "ем", s + "е")
    else:
        forms = (w, w + "а", w + "у", w + "а", w + ("ем" if w[-1] in _HUSH else "ом"), w + "е")
    return dict(zip(CASES, forms, strict=True))


def decl_phrase(parts: list[tuple[str, str]], gender: str) -> dict[str, str]:
    """Склонение составного имени: [(слово, kind), ...]."""
    per = [decl(w, gender, k) for w, k in parts]
    return {c: " ".join(p[c] for p in per) for c in CASES}


def adj_forms(masc: str) -> dict[str, str]:
    """Прилагательное цвета: мужской им. п. → формы женского рода (fn fg fd fa fi fp) + mn, ma."""
    soft = masc.endswith("ий") and masc[-3] not in "гкх"
    s = masc[:-2]
    if soft:
        f = dict(fn=s + "яя", fg=s + "ей", fd=s + "ей", fa=s + "юю", fi=s + "ей", fp=s + "ей")
    else:
        f = dict(fn=s + "ая", fg=s + "ой", fd=s + "ой", fa=s + "ую", fi=s + "ой", fp=s + "ой")
    f["mn"] = masc
    f["ma"] = masc
    return f


