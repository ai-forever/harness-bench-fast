def history(c: dict, attr: str) -> list:
    """Все значения атрибута за роман (библия, изменения, несостоявшиеся планы)."""
    vals = [c[_FIELD[attr]]]
    for _ch, key, a, new, _kind in CHANGES + PLANS:
        if key == c["key"] and a == attr:
            vals.append(new)
    return vals


def correct_display(R: random.Random, c: dict, attr: str, value, year: int):
    if attr == "AGE":
        return ("born", c["born"]) if R.random() < 0.3 else ("age", year - c["born"])
    if attr == "SIBLINGS":
        if not value:
            return ("none",)
        return ("sib", R.choice(value)) if R.random() < 0.7 else ("comp", value)
    if attr == "PATRONYMIC":
        return (c["patr"], c["father"][1])
    return value


def wrong_display(R: random.Random, c: dict, attr: str, value, year: int, avoid: list):
    """Ошибочный показ: значение, противоречащее `value` и не совпадающее ни с одним из `avoid`."""
    g = c["g"]
    if attr == "AGE":
        k = R.choice([-9, -7, -6, -5, -4, -3, 3, 4, 5, 6, 7, 10])
        if R.random() < 0.3:
            return ("born", c["born"] + k)
        return ("age", max(15, year - c["born"] + k))
    if attr == "EYES":
        return R.choice([e for e in EYES if e != value])
    if attr == "HAND":
        return "правша" if value == "левша" else "левша"
    if attr == "HOMETOWN":
        return R.choice([x for x in CITIES if x != value])
    if attr == "JOB":
        return R.choice([j for j in JOBS if j not in avoid])
    if attr == "SIBLINGS":
        if not value:
            sex = R.choice("mf")
            fake = (sex, R.choice(["older", "younger"]), R.choice(_SIB_NAMES[sex]))
            return ("sib", fake) if R.random() < 0.6 else ("comp", [fake])
        roll = R.random()
        if roll < 0.3:
            return ("none",)
        sib = R.choice(value)
        sex, rel, name = sib
        if roll < 0.6:
            return ("sib", (sex, "younger" if rel == "older" else "older", name))
        names = {s[2] for s in value}
        return ("sib", (sex, rel, R.choice([n for n in _SIB_NAMES[sex] if n not in names])))
    if attr == "PET":
        if value is None or None in avoid or R.random() < 0.8:
            sp = value[0] if value is not None and R.random() < 0.7 else R.choice(list(SPECIES))
            used = {v[1] for v in avoid if v} | _ALL_PET_NAMES
            return (sp, R.choice([n for n in PET_NAMES[sp] if n not in used]))
        return None
    if attr == "CAR":
        if value is None or None in avoid or R.random() < 0.85:
            for _ in range(100):
                if value is not None and R.random() < 0.5:
                    cand = (value[0], R.choice(COLORS)) if R.random() < 0.5 else (R.choice(CAR_MAKES), value[1])
                else:
                    cand = (R.choice(CAR_MAKES), R.choice(COLORS))
                if cand not in avoid:
                    return cand
        return None
    if attr == "ALLERGY":
        if value is None or R.random() < 0.8:
            return R.choice([a for a in ALLERGENS if a != value])
        return None
    if attr == "SCAR":
        if value is None or None in avoid or R.random() < 0.8:
            return R.choice([s for s in SCARS if s not in avoid])
        return None
    if attr == "PATRONYMIC":
        pool = [p for p in _PATR_POOL[g] if p[0][0] != c["patr"][0]]
        return R.choice(pool)
    raise AssertionError(attr)


def pick_tpl(R: random.Random, lst: list[str], tags: set[str], *, no_pos: bool = False,
             no_dialog: bool = False) -> str:
    cands = []
    for t in lst:
        body, tag = split_tag(t)
        if tag and tag not in tags:
            continue
        if no_pos and "{T.pos}" in body:
            continue
        if no_dialog and body.lstrip("!").startswith("—"):
            continue
        cands.append(body)
    return R.choice(cands)


def mention_tpl_vals(R: random.Random, c: dict, attr: str, disp, *, no_pos=False, no_dialog=False,
                     need: frozenset = frozenset()):
    """Шаблон и подстановки для показа `disp` атрибута `attr` персонажа `c`."""
    g = c["g"]
    tags = {g}
    kw = dict(no_pos=no_pos, no_dialog=no_dialog)
    if attr == "AGE":
        kind, n = disp
        lst = [t for t in M_AGE if ("{v.born}" in t) == (kind == "born")]
        vals = age_vals(n if kind == "age" else 30, n if kind == "born" else 1990)
        return pick_tpl(R, lst, tags, **kw), vals
    if attr == "EYES":
        return pick_tpl(R, M_EYES, tags, **kw), eyes_vals(disp, g)
    if attr == "HAND":
        return pick_tpl(R, M_HAND, tags | {"L" if disp == "левша" else "R"}, **kw), hand_vals(disp)
    if attr == "HOMETOWN":
        return pick_tpl(R, M_CITY, tags, **kw), city_vals(disp)
    if attr == "JOB":
        return pick_tpl(R, M_JOB, tags, **kw), job_vals(disp, g)
    if attr == "SIBLINGS":
        if disp[0] == "none":
            return pick_tpl(R, M_SIB_NONE, tags, **kw), {}
        if disp[0] == "comp":
            return pick_tpl(R, M_SIB_COMP, tags, **kw), {"comp": sib_comp(disp[1])}
        return pick_tpl(R, M_SIB, tags, **kw), sib_vals(disp[1])
    if attr == "PET":
        if disp is None:
            return pick_tpl(R, M_PET_NONE, tags, **kw), {}
        sp = {"пёс": "dog", "кот": "cat", "кошка": "cat", "попугай": "parrot"}[disp[0]]
        return pick_tpl(R, M_PET, tags | {sp}, **kw), pet_vals(disp)
    if attr == "CAR":
        if disp is None:
            return pick_tpl(R, M_CAR_NONE, tags, **kw), {}
        lst = [t for t in M_CAR if ("make" not in need or "{v.m_" in t) and ("color" not in need or "{v.c_f" in t)]
        return pick_tpl(R, lst, tags, **kw), car_vals(disp)
    if attr == "ALLERGY":
        if disp is None:
            return pick_tpl(R, M_ALLERGY_NONE, tags, **kw), {}
        return pick_tpl(R, M_ALLERGY, tags | {ALLERGENS[disp][1]}, **kw), allergy_vals(disp)
    if attr == "SCAR":
        if disp is None:
            return pick_tpl(R, M_SCAR_NONE, tags, **kw), {}
        grp = SCARS[disp]
        extra = {"limb"} if grp in ("arm", "hand") else {"leg"} if grp == "leg" else set()
        return pick_tpl(R, M_SCAR, tags | extra, **kw), scar_vals(disp)
    if attr == "PATRONYMIC":
        patr, fa_i = disp
        return pick_tpl(R, M_PATR, tags, **kw), patr_vals(c, patr, fa_i)
    raise AssertionError(attr)


def prefixed(prefix: str, vals: dict[str, str]) -> dict[str, str]:
    return {(k if k.startswith("_") else prefix + k): v for k, v in vals.items()}


def value_at(c: dict, attr: str, pos: tuple[int, int], change_pos: dict) -> object:
    """Значение атрибута в настоящем времени романа на позиции `pos` (глава, абзац)."""
    v = c[_FIELD[attr]]
    for (key, a), (cpos, new) in change_pos.items():
        if key == c["key"] and a == attr and cpos <= pos:
            v = new
    return v


def job_entry(kind, key, attr, disp=None, *, error=False, cat="regular", **kw):
    return dict(kind=kind, key=key, attr=attr, disp=disp, error=error, cat=cat, **kw)


@functools.cache
def build() -> dict:
    """Модель рукописи: главы → абзацы (текст), список упоминаний с разметкой ошибок."""
    R = rng(TASK_ID)
    n_par = {ch: R.randint(67, 71) for ch in range(1, N_CHAPTERS + 1)}
    flash, flash_jobs = build_flashbacks(R, n_par)

    def in_flash(ch: int, i: int) -> bool:
        f = flash.get(ch)
        return bool(f) and f["start"] <= i <= f["end"]

    present = [(ch, i) for ch in n_par for i in range(1, n_par[ch] + 1) if not in_flash(ch, i)]
    jobs: dict[tuple[int, int], dict] = dict(flash_jobs)

    def take(lo: tuple[int, int], hi: tuple[int, int]) -> tuple[int, int]:
        cands = [p for p in present if lo <= p < hi and p not in jobs]
        return R.choice(cands)

    # --- легальные изменения и несостоявшиеся планы
    change_pos: dict[tuple[str, str], tuple[tuple[int, int], object]] = {}
    change_info = []
    for ch, key, attr, new, kind in CHANGES:
        pos = take((ch, 8), (ch, n_par[ch] - 5))
        old = BY_KEY[key][_FIELD[attr]]
        jobs[pos] = job_entry("change", key, attr, cat="change", ckind=kind, old=old, new=new)
        change_pos[(key, attr)] = (pos, new)
        change_info.append((pos, key, attr, old, new, kind))
    plan_info = []
    for ch, key, attr, planned, kind in PLANS:
        pos = take((ch, 8), (ch, n_par[ch] - 5))
        jobs[pos] = job_entry("plan", key, attr, cat="plan", pkind=kind, planned=planned)
        plan_info.append((pos, key, attr, planned, kind))
    end = (N_CHAPTERS + 1, 0)

    # --- ошибки, связанные с изменениями
    for pos, key, attr, old, new, kind in change_info:
        c = BY_KEY[key]
        hi = (min(pos[0] + 6, N_CHAPTERS + 1), 0)
        p2 = take((pos[0], pos[1] + 1), hi)
        jobs[p2] = job_entry("mention", key, attr, correct_display(R, c, attr, old, YEAR), error=True,
                             cat="stale")
        for _ in range(2):  # верные упоминания нового значения после изменения
            p3 = take((pos[0], pos[1] + 1), end)
            jobs[p3] = job_entry("mention", key, attr, correct_display(R, c, attr, new, YEAR),
                                 cat="post_change_ok")
        if kind in PASTREF:
            p4 = take((pos[0], pos[1] + 1), end)
            jobs[p4] = job_entry("pastref", key, attr, cat="pastref", ckind=kind, old=old, new=new)
    for key, attr in [("kovaleva", "CAR"), ("somova", "SCAR"), ("burtsev", "JOB")]:
        (pos, new) = change_pos[(key, attr)]
        p2 = take((1, 1), pos)
        jobs[p2] = job_entry("mention", key, attr, new, error=True, cat="premature")
    for pos, key, attr, planned, _kind in plan_info:
        p2 = take((pos[0], pos[1] + 1), (min(pos[0] + 6, N_CHAPTERS + 1), 0))
        jobs[p2] = job_entry("mention", key, attr, planned, error=True, cat="plan_err")
        p3 = take((pos[0], pos[1] + 1), end)
        c = BY_KEY[key]
        jobs[p3] = job_entry("mention", key, attr, correct_display(R, c, attr, c[_FIELD[attr]], YEAR),
                             cat="post_plan_ok")

    # --- ошибочные предположения, опровергнутые в том же абзаце
    misc_attrs = list(MISC) + R.sample(list(MISC), 3)
    for attr in misc_attrs:
        key = R.choice(CHARS)["key"]
        jobs[take((1, 1), end)] = job_entry("misc", key, attr, cat="misc")

    # --- обычные упоминания: верные и ошибочные
    err_attrs = list(ATTRS) * 2 + ["AGE", "EYES", "SIBLINGS"]
    err_keys = [c["key"] for c in CHARS] * 2
    R.shuffle(err_keys)
    regular = []
    for attr, key in zip(err_attrs, err_keys, strict=False):
        regular.append((key, attr, True))
    for c in CHARS:
        for attr in ATTRS:
            for _ in range(R.choice([1, 2, 2, 2, 3])):
                regular.append((c["key"], attr, False))
    R.shuffle(regular)
    for key, attr, err in regular:
        pos = take((1, 1), end)
        c = BY_KEY[key]
        cur = value_at(c, attr, pos, change_pos)
        if err:
            disp = wrong_display(R, c, attr, cur, YEAR, history(c, attr))
        else:
            disp = correct_display(R, c, attr, cur, YEAR)
        jobs[pos] = job_entry("mention", key, attr, disp, error=err)

    return render_world(R, n_par, flash, jobs, change_pos)


def build_flashbacks(R: random.Random, n_par: dict[int, int]) -> tuple[dict, dict]:
    """Флешбэки: верный возраст на год флешбэка, неизменяемые атрибуты, свободные прежние значения."""
    err_plan = {6: ("gladkova", "EYES"), 12: ("uvarov", "HOMETOWN"), 15: ("sychev", "AGE_PRESENT")}
    flash, jobs = {}, {}
    for ch, title, year, keys in FLASHBACKS:
        fj = []
        for key in keys:
            c = BY_KEY[key]
            fj.append(job_entry("mention", key, "AGE", ("age", year - c["born"]), cat="flash_age_ok"))
            for attr in R.sample(["EYES", "HAND", "HOMETOWN", "PATRONYMIC"], R.choice([1, 2])):
                fj.append(job_entry("mention", key, attr, correct_display(R, c, attr, c[_FIELD[attr]], year),
                                    cat="flash_imm"))
            free = [a for a in ("CAR", "JOB", "PET", "ALLERGY") if a != "ALLERGY" or c["allergy"]]
            if c["scar"]:
                free.append("SCAR")
            for attr in R.sample(free, 2):
                if attr in ("SCAR", "ALLERGY"):
                    disp = None
                else:
                    disp = wrong_display(R, c, attr, c[_FIELD[attr]], year, history(c, attr))
                    if disp is None:
                        disp = wrong_display(R, c, attr, None, year, history(c, attr))
                fj.append(job_entry("mention", key, attr, disp, cat="flash_free"))
        if ch in err_plan:
            key, attr = err_plan[ch]
            c = BY_KEY[key]
            if attr == "AGE_PRESENT":
                fj.append(job_entry("mention", key, "AGE", ("age", YEAR - c["born"]), error=True,
                                    cat="flash_age_err"))
            else:
                disp = wrong_display(R, c, attr, c[_FIELD[attr]], year, [c[_FIELD[attr]]])
                fj.append(job_entry("mention", key, attr, disp, error=True, cat="flash_err"))
        R.shuffle(fj)
        ln = len(fj) + R.randint(2, 3)
        start = R.randint(16, n_par[ch] - ln - 8)
        flash[ch] = dict(start=start, end=start + ln - 1, title=title, year=year, keys=keys)
        slots = sorted(R.sample(range(start + 1, start + ln), len(fj)))
        for s, j in zip(slots, fj, strict=True):
            j["flash_year"] = year
            jobs[(ch, s)] = j
    return flash, jobs


