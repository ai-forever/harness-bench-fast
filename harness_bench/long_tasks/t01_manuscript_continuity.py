PROMPT = """\
Ты — корректор издательства. В папке `manuscript/` лежит рукопись романа «Тополиный пух»
(`ch01.md` … `ch18.md`), каждый абзац начинается со своего номера вида `[¶07-023]`. В `bible.md` —
библия персонажей (их состояние на начало романа), в `style.md` — правила: что считается ошибкой
непрерывности, коды атрибутов, как учитывать изменения по ходу сюжета, флешбэки и реплики.

Найди все ошибки непрерывности: абзацы, где текст утверждает о персонаже из библии что-то,
противоречащее библии или изменению, которое к этому месту уже произошло в тексте.

Результат запиши в `errors.csv` (UTF-8) в корне рабочей папки, с заголовком
`paragraph,character,attribute`: номер абзаца в виде `07-023`, каноническое имя персонажа из
заголовка его карточки в библии («Имя Фамилия») и код атрибута из `style.md`. Одна строка —
одна ошибка. Оцениваются точность и полнота.

Рукопись большая (около полумиллиона символов), написана свободной прозой: персонажей называют
по-разному (уменьшительными, по фамилии, по имени-отчеству, местоимениями), значения атрибутов
встречаются в разных формах. Учитывать нужно каждую главу и каждый абзац. Файлы рукописи,
библии и правил не изменяй.
"""


def _inputs(w: dict) -> dict[str, str]:
    files = {"bible.md": bible_md(), "style.md": STYLE_MD}
    for ch, text in w["chapters"].items():
        files[f"manuscript/ch{ch:02d}.md"] = text
    return files


def setup(ws: Path) -> None:
    for rel, text in _inputs(build()).items():
        write(ws, rel, text)


def _write_errors(ws: Path, rows) -> None:
    write_csv(ws, "errors.csv", ["paragraph", "character", "attribute"], sorted(rows))


def gold(ws: Path) -> None:
    _write_errors(ws, build()["gold"])


def _name_map() -> dict[str, str]:
    out = {}
    for c in CHARS:
        for v in (f"{c['first']} {c['sur']}", f"{c['sur']} {c['first']}",
                  f"{c['first']} {c['patr']} {c['sur']}", f"{c['sur']} {c['first']} {c['patr']}"):
            out[_nkey(v)] = canon(c)
    return out


def _nkey(s: str) -> str:
    return re.sub(r"\s+", " ", s.replace("ё", "е").replace("Ё", "Е")).strip().casefold()


_PID = re.compile(r"(\d{1,2})\s*-\s*(\d{1,3})")


def check(ws: Path) -> str:
    w = build()
    for rel, text in _inputs(w).items():
        path = ws / rel
        assert path.is_file() and path.read_text(encoding="utf-8") == text, f"входной файл {rel} изменён"
    rows = read_csv(ws, "errors.csv", ["paragraph", "character", "attribute"])
    names = _name_map()
    got = set()
    for r in rows:
        m = _PID.search(r["paragraph"])
        pid = f"{int(m.group(1)):02d}-{int(m.group(2)):03d}" if m else r["paragraph"]
        who = names.get(_nkey(r["character"]), r["character"])
        got.add((pid, who, r["attribute"].strip().upper()))
    expected = set(w["gold"])
    p, rc = precision_recall(expected, got)
    note = f"точность {p:.1%}, полнота {rc:.1%} (строк в отчёте {len(got)})"
    assert p + 1e-9 >= MIN_P and rc + 1e-9 >= MIN_R, (
        f"{note}; нужно не меньше {MIN_P:.0%} и {MIN_R:.0%}")
    return note


