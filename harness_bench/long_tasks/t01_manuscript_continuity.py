def _triple(r: dict) -> tuple[str, str, str]:
    return (r["para"], canon(BY_KEY[r["key"]]), r["attr"])


def _pos(pid: str) -> tuple[int, int]:
    a, b = pid.split("-")
    return (int(a), int(b))


def ignore_changes(ws: Path) -> None:
    """Сверяет всё только с библией: пропускает устаревшие значения, ругает новые."""
    w = build()
    rows = set(w["gold"])
    for r in w["rec"]:
        if r["cat"] == "stale":
            rows.discard(_triple(r))
        cp = w["change_pos"].get((r["key"], r["attr"]))
        if cp and r["cat"] in ("regular", "post_change_ok") and not r["error"] and _pos(r["para"]) >= cp[0]:
            rows.add(_triple(r))
    _write_errors(ws, rows)


def flashback_blind(ws: Path) -> None:
    """Проверяет флешбэки как настоящее время."""
    w = build()
    rows = set(w["gold"])
    for r in w["rec"]:
        if r["cat"] == "flash_age_err":
            rows.discard(_triple(r))
        if r["cat"] in ("flash_age_ok", "flash_free"):
            rows.add(_triple(r))
    _write_errors(ws, rows)


def literal_reader(ws: Path) -> None:
    """Не учитывает опровержения, планы и упоминания прежних значений."""
    w = build()
    rows = set(w["gold"])
    for r in w["rec"]:
        if r["cat"] in ("misc", "pastref", "plan"):
            rows.add(_triple(r))
    _write_errors(ws, rows)


def off_by_one(ws: Path) -> None:
    rows = {(f"{a}-{int(b) + 1:03d}", c, t) for (p, c, t) in build()["gold"] for a, b in [p.split("-")]}
    _write_errors(ws, rows)


def _all_forms(c: dict) -> list[str]:
    forms = set()
    for al, _w in aliases(c):
        forms.update(al.values())
    return sorted(forms, key=len, reverse=True)


_NUMW = {w: i for i, w in enumerate(_UNITS) if w}
_NUMW.update({w: 10 + i for i, w in enumerate(_TEENS)})
_NUMW.update({w: 10 * i for i, w in enumerate(_TENS) if w})


def _parse_num(words: list[str]) -> int | None:
    total, ok = 0, False
    for wd in words:
        if wd in _NUMW:
            total += _NUMW[wd]
            ok = True
        else:
            break
    return total if ok else None


def naive_keywords(ws: Path) -> None:
    """Скрипт на ключевых словах: первое имя в абзаце + сверка найденных значений с библией."""
    name_re = {c["key"]: re.compile(r"\b(" + "|".join(map(re.escape, _all_forms(c))) + r")\b") for c in CHARS}
    rows = set()
    for rel in sorted((ws / "manuscript").glob("ch*.md")):
        for line in rel.read_text(encoding="utf-8").splitlines():
            m = re.match(r"\[¶(\d\d-\d\d\d)\] (.*)", line)
            if not m:
                continue
            pid, text = m.groups()
            hits = [(mm.start(), k) for k, rx in name_re.items() if (mm := rx.search(text))]
            if not hits:
                continue
            c = BY_KEY[min(hits)[1]]
            low = text.lower()
            e = re.search(r"(сер|голуб|зелён|кар)(ые|ых|ыми|ие|их|ими|оглаз|еглаз)", low)
            if e and "глаз" in low and not c["eyes"].startswith(e.group(1)):
                rows.add((pid, canon(c), "EYES"))
            h = re.search(r"(левш|правш)", low)
            if h and not c["hand"].startswith(h.group(1)):
                rows.add((pid, canon(c), "HAND"))
            t = re.search(r"(?:родом из|уроженка|уроженец|родил\w* в|вырос\w* в) (\w+)", text)
            if t and not t.group(1).startswith(c["city"][:4]):
                rows.add((pid, canon(c), "HOMETOWN"))
            mk = re.search(r"«(\w+)»", text)
            if mk and mk.group(1)[:3] in {x[:3] for x in CAR_MAKES} and (not c["car"] or mk.group(1)[:3] != c["car"][0][:3]):
                rows.add((pid, canon(c), "CAR"))
            for sp, names in PET_NAMES.items():
                for nm in names:
                    if re.search(r"\b" + nm[:-1], text) and (not c["pet"] or c["pet"][1] != nm) and sp:
                        rows.add((pid, canon(c), "PET"))
            al = re.search(r"аллерги\w* на (\w+)", low)
            if al and (not c["allergy"] or not ALLERGENS[c["allergy"]][0].startswith(al.group(1)[:4])):
                rows.add((pid, canon(c), "ALLERGY"))
            sc = re.search(r"шрам (\w+ \w+)", low)
            if sc and (not c["scar"] or not c["scar"].startswith(sc.group(1)[:6])):
                rows.add((pid, canon(c), "SCAR"))
            for jw in JOBS:
                form = JOBS[jw][c["g"]]
                if any(re.search(r"\b" + re.escape(f) + r"\b", text) for f in form.values()) and jw != c["job"]:
                    rows.add((pid, canon(c), "JOB"))
            ag = re.search(r"(?:было|был|свои|Мне) ((?:\w+ ?){1,2})", text)
            if ag and (n := _parse_num(ag.group(1).split())) and n != YEAR - c["born"]:
                rows.add((pid, canon(c), "AGE"))
            by = re.search(r"родил\w* в (\d{4})", text)
            if by and int(by.group(1)) != c["born"]:
                rows.add((pid, canon(c), "AGE"))
            pt = re.search(re.escape(c["first"]) + r" (\w+(?:вич|вна|ична))\b", text)
            if pt and pt.group(1) != c["patr"]:
                rows.add((pid, canon(c), "PATRONYMIC"))
    _write_errors(ws, rows)


def drop_flashback_and_dialogue(ws: Path) -> None:
    """Пропускает ошибки во флешбэках и все ошибки, связанные с изменениями."""
    w = build()
    rows = {_triple(r) for r in w["rec"] if r["error"] and r["cat"] in ("regular",)}
    _write_errors(ws, rows)


