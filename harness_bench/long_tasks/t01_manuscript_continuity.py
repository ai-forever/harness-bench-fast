def num_words(n: int) -> str:
    assert 1 <= n < 100
    if n < 10:
        return _UNITS[n]
    if n < 20:
        return _TEENS[n - 10]
    t, u = divmod(n, 10)
    return _TENS[t] + (" " + _UNITS[u] if u else "")


def years_word(n: int) -> str:
    if 11 <= n % 100 <= 14:
        return "лет"
    if n % 10 == 1:
        return "год"
    if 2 <= n % 10 <= 4:
        return "года"
    return "лет"


def age_was(n: int) -> str:
    """«было сорок два года» / «был сорок один год»."""
    return ("был " if n % 10 == 1 and n % 100 != 11 else "было ") + num_words(n) + " " + years_word(n)


def cap(s: str) -> str:
    for i, ch in enumerate(s):
        if ch.isalpha():
            return s[:i] + ch.upper() + s[i + 1:]
    return s


