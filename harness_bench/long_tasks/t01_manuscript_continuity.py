STYLE_MD = """# Непрерывность: что считается ошибкой

Этот документ — правила корректуры непрерывности для рукописи в `manuscript/`. Библия персонажей —
`bible.md`. Задача корректора — найти каждый абзац, где текст утверждает о персонаже из библии то,
что противоречит его **актуальному** значению атрибута.

## Время действия

Настоящее время романа — лето 2023 года. Главы идут строго в хронологическом порядке, внутри главы —
в порядке номеров абзацев. К началу романа все персонажи уже отметили день рождения в 2023 году,
поэтому возраст в настоящем времени — это 2023 минус год рождения.

## Коды атрибутов

| Код | Атрибут | Что считается утверждением |
|---|---|---|
| AGE | возраст / год рождения | прямо названный возраст («ей было сорок», «в свои пятьдесят», «мне тридцать лет»), год рождения |
| EYES | цвет глаз | цвет глаз персонажа в любой форме: «серые глаза», «сероглазая», «в карих глазах» |
| HAND | ведущая рука | «левша», «правша», а также какой рукой персонаж пишет, расписывается, подписывает, бросает мяч |
| HOMETOWN | родной город | «родом из», «родился в», «уроженец», «вырос в», «родной город», «я из …», «я человек из …» |
| JOB | профессия | кем персонаж работает сейчас: «работал хирургом», «я бухгалтер», «как и положено повару» |
| SIBLINGS | братья и сёстры | их число, пол, кто старше/младше, имена; «единственный ребёнок в семье» |
| PET | питомцы | вид и кличка питомца персонажа; утверждение, что животных у него нет |
| CAR | машина | марка и/или цвет машины персонажа; утверждение, что машины у него нет |
| ALLERGY | аллергия | на что у персонажа аллергия; утверждение, что аллергии нет |
| SCAR | шрамы | где у персонажа шрам; утверждение, что шрамов нет |
| PATRONYMIC | отчество | отчество в обращении, в полном имени, в инициалах («Лемешев Г. П.»), а также имя отца |

Библия перечисляет **все** питомцы, аллергии, шрамы, братьев и сестёр персонажа. Поэтому
упоминание питомца, аллергии, шрама, брата или сестры, которых нет в актуальном состоянии, — ошибка;
утверждение «животных нет», «аллергий нет», «ни одного шрама», «единственный ребёнок» при
наличии соответствующего — тоже ошибка. Утверждение о брате или сестре ошибочно, если не совпадает
пол, старшинство или имя.

## Что не является утверждением об атрибуте

- Какой рукой персонаж держит, несёт, чешет, поправляет, машет — не утверждение о ведущей руке.
- Поездки, командировки, открытки, звонки и новости из других городов — не утверждение о родном
  городе.
- Цвет одежды, зонтов, чужих машин, «круги перед глазами», «пробежал глазами» — не утверждения.
- Люди без карточки в библии (соседи, продавщицы, таксисты, братья и сёстры персонажей и т. п.)
  не проверяются, их машины, питомцы и аллергии тоже.

## Реплики, вопросы и опровержения

Реплика персонажа или вопрос, который предполагает факт («Откуда у тебя шрам на шее?»), — такое же
утверждение, как слова автора. Исключение: если **в том же абзаце** ошибочное предположение явно
опровергнуто и названо верное значение («— Вы ведь из Самары? — Нет, я из Твери»; «он был уверен,
что глаза у неё карие, но, присмотревшись, понял, что ошибался: они были серые»), это не ошибка.
Прикидка возраста на глаз, тут же поправленная автором, — тоже не ошибка.

## Легальные изменения

По ходу романа некоторые атрибуты меняются, и текст прямо описывает, что это **произошло**: машину
перекрасили, продали или купили новую, персонаж уволился и начал работать кем-то другим, завёл
питомца, питомец умер и появился новый, персонаж получил травму и у него остался шрам. Начиная с
абзаца, где изменение описано, актуально новое значение; до этого абзаца — прежнее (из библии или
от предыдущего изменения). Значит, после изменения старое значение, поданное как текущее, — ошибка,
а новое значение, упомянутое раньше, чем изменение произошло, — тоже ошибка.

- Намерения и планы, которые не осуществились («собирался перекрасить машину, но передумал»,
  «написал заявление, но забрал его обратно»), ничего не меняют.
- Прежнее значение, явно поданное как прежнее («прежде работала бухгалтером», «скучал по своей
  старой машине», «вспоминал покойного пса», «проступал прежний цвет»), — не ошибка.

## Флешбэки

Флешбэк — раздел, который открывается отдельной строкой-заголовком в звёздочках с указанием времени
(«*Двадцать лет назад*», «*Лето 1998 года*») и продолжается до строки `* * *` или до конца главы.
«N лет назад» отсчитывается от 2023 года. Внутри флешбэка:

- AGE проверяется относительно года флешбэка: возраст = год флешбэка − год рождения;
- EYES, HAND, HOMETOWN и PATRONYMIC проверяются как обычно;
- JOB, CAR, PET, SCAR, ALLERGY и SIBLINGS не проверяются: тогда всё могло быть иначе;
- изменения, случившиеся в настоящем времени романа, на флешбэк не влияют.

## Отчёт

Файл `errors.csv` в корне рабочей папки, UTF-8, с заголовком:

```
paragraph,character,attribute
07-023,Георгий Лемешев,CAR
```

- `paragraph` — номер абзаца без скобок и значка ¶: `ГГ-ААА`;
- `character` — каноническое имя из заголовка карточки библии («Имя Фамилия»);
- `attribute` — код из таблицы выше.

Одна строка — одна ошибка (абзац, персонаж, атрибут). Верные упоминания в отчёт не пишутся.
Оценка — точность и полнота по тройкам (абзац, персонаж, атрибут).
"""


