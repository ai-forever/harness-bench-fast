def _make_events_more(w: dict, gold: dict, r: random.Random, events: list, info: dict, tl, spk, nk) -> None:
    talks = w["talks"]

    def ev(t, slot, kind, data=None, sender=None, label="speaker", date=None):
        return _ev(events, tl, spk, t, slot, kind, data, sender, label, date)

    # ---- equipment ------------------------------------------------------
    plain = [t for t in nk if t not in w["sign"] and t not in w["access"]]
    need_talks = r.sample(plain, 28)
