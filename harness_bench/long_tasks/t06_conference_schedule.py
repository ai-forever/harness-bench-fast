def _make_people(r: random.Random, n: int) -> list[dict]:
    people: list[dict] = []
    surnames = list(SURNAMES)
    r.shuffle(surnames)
    sky = list(SURNAMES_SKY)
    used_first: set[str] = set()
    # two deliberate look-alike pairs (different people, different genders)
    specials = [("Лаптев", False), ("Лаптев", True), ("Кравцов", False), ("Кравцов", True)]
    for i in range(n):
        if i < len(specials):
            base, female = specials[i]
        else:
            base = sky.pop() if sky and r.random() < 0.08 else surnames.pop()
            female = r.random() < 0.4
        pool = FEMALE_FIRST if female else MALE_FIRST
        first = r.choice(pool)
        while (first[0], base) in used_first:
            first = r.choice(pool)
        used_first.add((first[0], base))
        patr = r.choice(PATRONYMICS)[1 if female else 0]
        org = r.choice(ORGS)
        person = make_person(f"P{i:02d}", first, patr, base, female, org)
        person["position"] = r.choice(POSITIONS)
        person["phone"] = f"+7 9{r.randint(10, 99)} {r.randint(100, 999)}-{r.randint(10, 99)}-{r.randint(10, 99)}"
        people.append(person)
    return people


def _free(w: dict, sched: dict, tid: str, day: int, start: int, room: str) -> bool:
    t = w["talks"][tid]
    end = start + t["dur"]
    for other, (d2, s2, r2) in sched.items():
        if d2 != day:
            continue
        e2 = s2 + w["talks"][other]["dur"]
        if s2 >= end or start >= e2:
            continue
        if r2 == room or w["talks"][other]["track"] == t["track"]:
            return False
        if w["persons"][other] & w["persons"][tid]:
            return False
    return True


def _starts(dur: int):
    for s0, s1 in SESSIONS:
        yield from range(max(s0, KEYNOTE_END), s1 - dur + 1, 30)


def _place_gold(w: dict, r: random.Random) -> dict | None:
    sched: dict[str, tuple[int, int, str]] = {}
    days = list(DAYS)
    r.shuffle(days)
    for k, d in zip(w["keynotes"], days, strict=True):
        sched[k] = (d, KEYNOTE_START, "A")
    others = [t for t in w["talks"] if t not in w["keynotes"]]
    special = [t for t in others if t in w["sign"] or t in w["access"]]
    rest = [t for t in others if t not in special]
    r.shuffle(rest)
    rest.sort(key=lambda t: -w["talks"][t]["dur"])
    load = {d: 0 for d in DAYS}
    for tid in special + rest:
        dur = w["talks"][tid]["dur"]
        if tid in w["sign"]:
            rooms = ["A"]
        elif tid in w["access"]:
            rooms = ["A", "B", "C"]
        else:
            rooms = list(ROOMS)
        cands = []
        for d in DAYS:
            for st in _starts(dur):
                if tid in w["sign"] and st + dur > 780:
                    continue
                for room in rooms:
                    if _free(w, sched, tid, d, st, room):
                        cands.append((d, st, room))
        if not cands:
            return None
        min_load = min(load[c[0]] for c in cands)
        good = [c for c in cands if load[c[0]] <= min_load + 60]
        pick = r.choice(good)
        sched[tid] = pick
        load[pick[0]] += dur
    return sched


def _base_world(r: random.Random) -> dict:
    people = _make_people(r, N_PEOPLE)
    pairs = [(tr, title) for tr in TRACKS for title in TITLES[tr]]
    r.shuffle(pairs)
    talks: dict[str, dict] = {}
    for i, title in enumerate(KEYNOTE_TITLES):
        talks[f"T{i + 1:02d}"] = {"track": KEYNOTE_TRACK, "title": title, "dur": 60}
    for i, (tr, title) in enumerate(pairs):
        dur = r.choices([30, 60, 90], weights=[35, 45, 20])[0]
        talks[f"T{i + 4:02d}"] = {"track": tr, "title": title, "dur": dur}
    tids = list(talks)
    # N_PEOPLE speakers for N_PEOPLE + 3 talks: three people present twice (never keynotes)
    order = list(range(N_PEOPLE))
    r.shuffle(order)
    for i, tid in enumerate(tids[:N_PEOPLE]):
        talks[tid]["speaker"] = people[order[i]]["key"]
    doubles = r.sample([t for t in tids[3:N_PEOPLE]], 3)
    for tid, extra in zip(doubles, tids[N_PEOPLE:], strict=True):
        talks[extra]["speaker"] = talks[tid]["speaker"]
    # shuffle ids once more so that doubled talks are not all at the end
    perm = tids[3:]
    r.shuffle(perm)
    talks = {**{t: talks[t] for t in tids[:3]}, **{f"T{i + 4:02d}": talks[p] for i, p in enumerate(perm)}}
    pmap = {p["key"]: p for p in people}
    talk_count: dict[str, int] = {}
    for t in talks.values():
        talk_count[t["speaker"]] = talk_count.get(t["speaker"], 0) + 1
    w = {
        "talks": talks,
        "people": pmap,
        "talk_count": talk_count,
        "keynotes": ["T01", "T02", "T03"],
        "persons": {tid: {t["speaker"]} for tid, t in talks.items()},
    }
    nk = [t for t in talks if t not in w["keynotes"]]
    w["sign"] = set(r.sample(nk, 3))
    w["access"] = set(r.sample([t for t in nk if t not in w["sign"]], 4))
    return w


