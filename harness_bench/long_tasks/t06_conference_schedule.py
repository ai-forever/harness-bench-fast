def gend(text: str, female: bool) -> str:
    if not female:
        return text
    text = text.replace("рассказывать один", "рассказывать одна")
    return re.sub(r"\b(" + "|".join(_FEM) + r")\b", lambda mm: _FEM[mm.group(1)], text)


