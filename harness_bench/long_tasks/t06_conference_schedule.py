_ROOM_ALIASES = {"А": "A", "В": "B", "С": "C", "Е": "E"}
_DAY_ALIASES = {"2026-10-13": 1, "2026-10-14": 2, "2026-10-15": 3, "13.10.2026": 1, "14.10.2026": 2, "15.10.2026": 3}


def check(ws: Path) -> str:
    b = build()
    model = b["model"]
    rows = read_csv(ws, "schedule.csv", required=["talk_id", "day", "start", "room"])
    sched: dict[str, tuple[int, int, str]] = {}
    for n, row in enumerate(rows, 2):
        t = row["talk_id"].strip().upper()
        assert t in model["dur"], f"schedule.csv:{n}: неизвестный доклад {t!r}"
        assert t not in sched, f"schedule.csv:{n}: доклад {t} встречается повторно"
        day_raw = row["day"].strip()
        day = int(day_raw) if day_raw.isdigit() else _DAY_ALIASES.get(day_raw)
        assert day in DAYS, f"schedule.csv:{n}: день должен быть 1, 2 или 3"
        st = parse_hm(row["start"])
        assert st is not None, f"schedule.csv:{n}: время начала не в формате ЧЧ:ММ"
        room = row["room"].strip().upper()
        room = _ROOM_ALIASES.get(room, room)
        assert room in ROOMS, f"schedule.csv:{n}: неизвестный зал {row['room']!r}"
        sched[t] = (day, st, room)
    missing = sorted(set(model["dur"]) - set(sched))
    assert not missing, f"в расписании нет {len(missing)} докладов, например {missing[0]}"
    bad = violations(sched, model)
    if bad:
        examples = "; ".join(msg for _, msg in bad[:4])
        raise AssertionError(f"нарушено жёстких ограничений: {len(bad)}. Примеры: {examples}")
    return f"все {len(sched)} докладов расставлены, нарушений нет"


