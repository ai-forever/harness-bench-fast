def translit(text: str) -> str:
    return "".join(TRANSLIT.get(ch, ch) for ch in text.lower())


def surname_forms(base: str, female: bool) -> tuple[str, str, str, str]:
    """nominative, genitive, dative, instrumental."""
    if base.endswith("ский"):
        stem = base[:-4]
        if female:
            return stem + "ская", stem + "ской", stem + "ской", stem + "ской"
        return base, stem + "ского", stem + "скому", stem + "ским"
    if female:
        return base + "а", base + "ой", base + "ой", base + "ой"
    return base, base + "а", base + "у", base + "ым"


def make_person(key: str, first: tuple, patr: str, sur: str, female: bool, org: tuple, email=None):
    sf = surname_forms(sur, female)
    return {
        "key": key,
        "female": female,
        "first": first[0],
        "first_f": first,
        "patr": patr,
        "sur": sf[0],
        "sur_f": sf,
        "org": org[0],
        "email": email or f"{translit(first[0][0])}.{translit(sf[0])}@{org[1]}",
        "nom": f"{first[0]} {sf[0]}",
        "gen": f"{first[1]} {sf[1]}",
        "dat": f"{first[2]} {sf[2]}",
        "ins": f"{first[3]} {sf[3]}",
        "full": f"{sf[0]} {first[0]} {patr}",
    }


