def hm(minutes: int) -> str:
    return f"{minutes // 60:02d}:{minutes % 60:02d}"


def parse_hm(text: str) -> int | None:
    text = text.strip()
    if ":" not in text:
        return None
    h, _, m = text.partition(":")
    if not (h.isdigit() and m.isdigit()):
        return None
    return int(h) * 60 + int(m)


def session_of(start: int, dur: int) -> int | None:
    for i, (s0, s1) in enumerate(SESSIONS):
        if s0 <= start and start + dur <= s1:
            return i
    return None


