def chair_item(r: random.Random, w: dict, e: dict) -> str:
    t, kind, data = e["talk"], e["kind"], e["data"]
    if kind == "closure":
        room, wins = data
        d, lo, hi = wins[0]
        if e["label"] == "chair_replace":
            return (f"Уточнение по залу {room} («{ROOM_NAME[room]}»): работы перенесли. Прежнее объявление о закрытии "
                    f"этого зала отменяется; теперь зал {room} {closure_phrase(r, d, lo, hi)}.")
        return f"Зал {room} («{ROOM_NAME[room]}») {closure_phrase(r, d, lo, hi)}: {r.choice(CLOSURE_REASON)}."
    tk = w["talks"][t]
    sp = w["people"][tk["speaker"]]
    if kind == "dur":
        return r.choice([
            f"Доклад {t} «{tk['title']}» ({sp['nom']}) продлеваем до {data} минут: рецензенты единодушно просили дать больше времени на разбор примеров.",
            f"По решению ПК длительность доклада {t} ({sp['gen']}) составит {data} минут вместо {tk['csv_dur']}.",
        ])
    if kind == "aud":
        return r.choice([
            f"На доклад {t} «{tk['title']}» по данным предварительной регистрации записались {data} человек; ожидаемую аудиторию прошу считать равной {data}.",
            f"Ожидаемую аудиторию доклада {t} ({sp['gen']}) поднимаем до {data} слушателей — регистрация идёт очень активно.",
        ])
    if kind == "avail":
        quote = gend(avail_sentence(r, data), sp["female"])
        return (f"По докладу {t} «{tk['title']}»: я лично созвонился с {sp['ins']} и мы договорились окончательно. "
                f"Это решение ПК: доклад ставим с учётом того, что сказал{'а' if sp['female'] else ''} докладчик: «{quote}»")
    if kind == "cosp":
        p = w["people"][data]
        return (f"В докладе {t} «{tk['title']}» вместе с {sp['ins']} выступит {p['nom']} — "
                f"прошу учесть это при расстановке.")
    raise ValueError(kind)


