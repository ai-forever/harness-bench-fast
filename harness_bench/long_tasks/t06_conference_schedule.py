def _secretary_sign(r: random.Random) -> str:
    return r.choice(SECRETARY_CLOSE) + "\n" + SECRETARY["sign"]


def _outsider(r: random.Random, domain: str, used: set) -> dict:
    while True:
        first, g = r.choice(OUTSIDERS_FIRST)
        sur = r.choice(OUTSIDER_SURNAMES)
        if (first, sur) not in used:
            used.add((first, sur))
            break
    female = g == "ж"
    sf = surname_forms(sur, female)
    return {"nom": f"{first} {sf[0]}", "female": female,
            "email": f"{translit(first[0])}.{translit(sf[0])}@{domain}", "sign": f"{first} {sf[0]}"}


def render_mail(w: dict, events: list[dict], r: random.Random, info: dict) -> list[dict]:
    qa, dur_reply, sec_sum = info["qa"], info["dur_reply"], info["sec_sum"]
    msgs: list[dict] = []
    talks = w["talks"]
    used: set = set()
    by_talk: dict[str, dict[str, list]] = {}
    for e in events:
        if e["kind"] == "cosp_ext":
            e["ext"] = _outsider(r, "example.org", used)
        if e["label"] in ("chair", "chair_replace", "qa", "chair_reply") or e["slot"] == "trap":
            continue
        by_talk.setdefault(e.get("host", e["talk"]), {"m1": [], "m3": []})[e["slot"]].append(e)
