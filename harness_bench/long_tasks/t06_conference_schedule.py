def talk_ref(r: random.Random, w: dict, tid: str, case: str) -> str:
    """case: 'ins' (с чем), 'gen' (после чего), 'acc' (что)."""
    t = w["talks"][tid]
    sp = w["people"][t["speaker"]]
    noun = {"ins": "докладом", "gen": "доклада", "acc": "доклад"}[case]
    noun2 = {"ins": "выступлением", "gen": "выступления", "acc": "выступление"}[case]
    options = [f"{noun} «{t['title']}»", f"{noun} {tid}"]
    if w["talk_count"][t["speaker"]] == 1:
        options += [f"{noun} {sp['gen']}", f"{noun2} {sp['gen']}", f"{noun} {sp['gen']} «{t['title']}»"]
    return r.choice(options)


