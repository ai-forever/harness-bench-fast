def derive(w: dict, events: list[dict]) -> dict:
    talks = w["talks"]
    email = {t: w["people"][talks[t]["speaker"]]["email"] for t in talks}
    m = {
        "dur": {t: talks[t]["csv_dur"] for t in talks},
        "aud": {t: talks[t]["csv_aud"] for t in talks},
        "track": {t: talks[t]["track"] for t in talks},
        "keynotes": set(w["keynotes"]),
        "avail": {},
        "needs": {t: {} for t in talks},
        "sign": set(),
        "np": {},
        "order": {},
        "cosp": {},
        "closures": {},
    }
    for e in sorted(events, key=lambda e: (e["date"], e["seq"])):
        t, kind, s = e["talk"], e["kind"], e["sender"]
        chair = s == CHAIR_EMAIL
        if kind in ("dur", "aud", "closure"):
            if not chair:
                continue
        elif not (chair or (t and s == email[t])):
            continue
        if kind == "avail":
            m["avail"][t] = dict(e["data"])
        elif kind == "need":
            m["needs"][t][e["data"]] = True
        elif kind == "need_del":
            m["needs"][t][e["data"]] = False
        elif kind == "sign":
            m["sign"].add(t)
        elif kind == "np":
            m["np"][frozenset((t, e["data"]))] = True
        elif kind == "np_del":
            m["np"][frozenset((t, e["data"]))] = False
        elif kind == "order_after":
            m["order"][(e["data"], t)] = True
        elif kind == "order_before":
            m["order"][(t, e["data"])] = True
        elif kind == "cosp":
            m["cosp"][(t, e["data"])] = True
        elif kind == "cosp_del":
            m["cosp"][(t, e["data"])] = False
        elif kind == "dur":
            m["dur"][t] = e["data"]
        elif kind == "aud":
            m["aud"][t] = e["data"]
        elif kind == "closure":
            room, wins = e["data"]
            m["closures"][room] = list(wins)
    m["needs"] = {t: {k for k, v in d.items() if v} for t, d in m["needs"].items()}
    m["np"] = {k for k, v in m["np"].items() if v}
    m["order"] = {k for k, v in m["order"].items() if v}
    persons = {t: {talks[t]["speaker"]} for t in talks}
    for (t, p), v in m["cosp"].items():
        if v:
            persons[t].add(p)
    m["persons"] = persons
    del m["cosp"]
    return m


def violations(sched: dict[str, tuple[int, int, str]], m: dict, only: str | None = None) -> list[tuple[frozenset, str]]:
    """Hard-constraint violations of a schedule under model `m` (optionally only those involving `only`)."""
    out: list[tuple[frozenset, str]] = []
    span = {}
    for t, (d, st, room) in sched.items():
        dur = m["dur"][t]
        en = st + dur
        span[t] = (d, st, en)
        one = frozenset((t,))
        if only is not None and t != only:
            continue
        if d not in DAYS or room not in ROOMS or st % 30:
            out.append((one, f"{t}: вне сетки"))
            continue
        if session_of(st, dur) is None:
            out.append((one, f"{t}: доклад пересекает перерыв или выходит за сессию"))
        if t in m["keynotes"]:
            if (st, room) != (KEYNOTE_START, "A"):
                out.append((one, f"{t}: пленарный доклад не в 09:00 в зале A"))
        elif st < KEYNOTE_END:
            out.append((one, f"{t}: доклад во время пленарного часа"))
        if ROOM_CAP[room] < m["aud"][t]:
            out.append((one, f"{t}: не хватает вместимости зала"))
        if not m["needs"][t] <= ROOM_EQ[room]:
            out.append((one, f"{t}: в зале нет нужного оборудования"))
        if t in m["sign"] and (room != "A" or en > 780):
            out.append((one, f"{t}: сурдоперевод возможен только в зале A до 13:00"))
        if not avail_fits(m["avail"].get(t), d, st, en):
            out.append((one, f"{t}: время недоступно докладчику"))
        for cd, lo, hi in m["closures"].get(room, []):
            if cd == d and st < hi and lo < en:
                out.append((one, f"{t}: зал {room} закрыт"))
    if only is None:
        per_day = {d: [t for t in m["keynotes"] if t in span and span[t][0] == d] for d in DAYS}
        for d, ks in per_day.items():
            if len(ks) != 1:
                out.append((frozenset(ks), f"день {d}: должен быть ровно один пленарный доклад"))
    ids = sorted(span)
    if only is not None:
        pairs = [(min(only, x), max(only, x)) for x in ids if x != only]
    else:
        pairs = [(a, b) for i, a in enumerate(ids) for b in ids[i + 1:]]
    for a, b in pairs:
        if not _overlap(span[a], span[b]):
            continue
        pair = frozenset((a, b))
        if sched[a][2] == sched[b][2]:
            out.append((pair, f"{a} и {b}: один зал одновременно"))
        if m["track"][a] == m["track"][b]:
            out.append((pair, f"{a} и {b}: один трек одновременно"))
        if m["persons"][a] & m["persons"][b]:
            out.append((pair, f"{a} и {b}: один человек в двух местах"))
        if pair in m["np"]:
            out.append((pair, f"{a} и {b}: просили не ставить параллельно"))
    for a, b in m["order"]:
        if a in span and b in span and (only is None or only in (a, b)):
            ea = span[a][0] * 1440 + span[a][2]
            sb = span[b][0] * 1440 + span[b][1]
            if ea > sb:
                out.append((frozenset((a, b)), f"{a} должен идти раньше {b}"))
    return out


