BULLETINS = [_dt.datetime(2026, 9, 8, 18, 5), _dt.datetime(2026, 9, 23, 19, 40), _dt.datetime(2026, 10, 6, 17, 15)]
LAST_DATE = _dt.datetime(2026, 10, 9, 20, 0)


def _windows_for(st: int, en: int) -> list[tuple[int, int]]:
    c = []
    if en <= 780:
        c.append((540, 780))
    if st >= 840:
        c.append((840, 1080))
    if st >= 990:
        c.append((990, 1080))
    for lo in (690, 750, 870, 900, 1020):
        if 600 < lo <= st and lo not in (840, 990):
            c.append((lo, 1080))
    for hi in (720, 900, 960, 1020):
        if en <= hi:
            c.append((540, hi))
    return c


def _true_avail(r: random.Random, day: int, st: int, en: int, kind: str) -> dict:
    others = [d for d in DAYS if d != day]
    if kind == "only1":
        return {day: FULL}
    if kind == "only2":
        return {day: FULL, r.choice(others): FULL}
    win = r.choice(_windows_for(st, en))
    if kind == "win1":
        return {day: win}
    return {day: win, r.choice(others): FULL}


def _span(w: dict, gold: dict, tid: str, dur: int | None = None) -> tuple[int, int, int]:
    d, st, _ = gold[tid]
    return d, st, st + (dur if dur is not None else w["talks"][tid]["dur"])


def _overlap(a: tuple, b: tuple) -> bool:
    return a[0] == b[0] and a[1] < b[2] and b[1] < a[2]


def _ev(events, tl, spk, t, slot, kind, data=None, sender=None, label="speaker", date=None) -> dict:
    e = {
        "talk": t, "slot": slot, "kind": kind, "data": data, "label": label,
        "sender": sender if sender is not None else (spk[t]["email"] if t else CHAIR_EMAIL),
        "date": date if date is not None else tl[t][slot], "seq": len(events),
    }
    events.append(e)
    return e


def _make_events(w: dict, gold: dict, r: random.Random) -> tuple:
    talks = w["talks"]
    nk = [t for t in talks if t not in w["keynotes"]]
    spk = {t: w["people"][talks[t]["speaker"]] for t in talks}
    events: list[dict] = []
    info: dict = {"sup": {}, "unauth": {}, "chair_dur": {}, "shorten": {}, "cosp": [], "np": [], "order": []}

    # per-talk timeline
    def wh(d):
        return d.replace(hour=8 + d.hour % 14)

    tl = {}
    for t in talks:
        d1 = _dt.datetime(2026, 8, 17, 9, 0) + _dt.timedelta(days=r.randint(0, 30), minutes=r.randint(0, 600))
        d2 = d1 + _dt.timedelta(days=r.randint(1, 3), minutes=r.randint(10, 300))
        d3 = d2 + _dt.timedelta(days=r.randint(3, 12), minutes=r.randint(10, 400))
        trap = d3 + _dt.timedelta(days=r.randint(2, 7), minutes=r.randint(10, 300))
        d1, d2, d3, trap = wh(d1), wh(d2), wh(d3), wh(trap)
        d3 = max(d3, d2 + _dt.timedelta(days=1))
        trap = max(trap, d3 + _dt.timedelta(days=1))
        tl[t] = {"m1": d1, "m2": d2, "m3": d3, "trap": min(trap, LAST_DATE)}

    def ev(t, slot, kind, data=None, sender=None, label="speaker", date=None):
        return _ev(events, tl, spk, t, slot, kind, data, sender, label, date)

    # ---- availability -------------------------------------------------
    for k in w["keynotes"]:
        ev(k, "m1", "avail", {gold[k][0]: FULL})
    # a person with two talks would make "I am only here on Wednesday" ambiguous — keep them out
    avail_nk = r.sample([t for t in nk if w["talk_count"][talks[t]["speaker"]] == 1], 40)
    pool = list(avail_nk)
    sup = pool[:13]
    selfcorr = pool[13:17]
    chair_av = pool[17:19]
    unauth = r.sample(sup[:8], 5) + r.sample(pool[19:], 5)
    kinds = ["only1"] * 12 + ["only2"] * 11 + ["win1"] * 9 + ["mixed"] * 8
    r.shuffle(kinds)
    for t, kind in zip(avail_nk, kinds, strict=True):
        d, st, en = _span(w, gold, t)
        av = _true_avail(r, d, st, en, kind)
        if t in sup:
            s0 = avail_disjoint(r, av)
            ev(t, "m1", "avail", s0)
            ev(t, "m3", "avail", av, label="supersede")
            info["sup"][t] = s0
        elif t in selfcorr:
            ev(t, "m1", "avail", av, label="selfcorr").update(wrong=avail_disjoint(r, av))
        elif t in chair_av:
            s0 = avail_disjoint(r, av)
            if t == chair_av[0]:
                ev(t, "m1", "avail", s0)
                info["sup"][t] = s0
            ev(t, "B", "avail", av, sender=CHAIR_EMAIL, label="chair", date=BULLETINS[1])
        else:
            ev(t, r.choice(["m1", "m1", "m3"]), "avail", av)
        if t in unauth:
            trap = avail_disjoint(r, av)
            labels = ["colleague", "assistant", "other_speaker", "vice", "secretary", "personal"]
            label = labels[len(info["unauth"]) % len(labels)]
            info["unauth"][t] = trap
            ev(t, "trap", "avail", trap, sender=f"trap:{label}", label=label)

    # ---- people ------------------------------------------------------
    used_pairs: set[frozenset] = set()

    def pick_pair(pred, tries=4000):
        for _ in range(tries):
            a, b = r.sample(nk, 2)
            key = frozenset((a, b))
            if key in used_pairs or talks[a]["speaker"] == talks[b]["speaker"]:
                continue
            if pred(a, b):
                used_pairs.add(key)
                return a, b
        raise RuntimeError("pair not found")

    def near_same_day(a, b):
        sa, sb = _span(w, gold, a), _span(w, gold, b)
        if _overlap(sa, sb) or sa[0] != sb[0]:
            return False
        gap = max(sb[1] - sa[2], sa[1] - sb[2])
        return gap <= 60 and talks[a]["track"] != talks[b]["track"]

    for _ in range(18):
        a, b = pick_pair(near_same_day)
        ev(a, r.choice(["m1", "m3"]), "np", b)
        info["np"].append((a, b))
    for _ in range(4):
        a, b = pick_pair(lambda a, b: _overlap(_span(w, gold, a), _span(w, gold, b)))
        ev(a, "m1", "np", b)
        ev(a, "m3", "np_del", b)
    for i in range(6):
        def before(a, b):
            sa, sb = _span(w, gold, a), _span(w, gold, b)
            return sa[0] == sb[0] and 0 <= sb[1] - sa[2] <= 120
        a, b = pick_pair(before)
        # speaker of the later talk asks to follow, or the earlier asks to precede
        if i % 2 == 0:
            ev(b, r.choice(["m1", "m3"]), "order_after", a)
        else:
            ev(a, r.choice(["m1", "m3"]), "order_before", b)
        info["order"].append((a, b))
    a, b = pick_pair(lambda a, b: _overlap(_span(w, gold, a), _span(w, gold, b)))
    ev(b, "m1", "cosp", talks[a]["speaker"])
    ev(b, "m3", "cosp_del", talks[a]["speaker"])
    for _ in range(4):
        t = r.choice(nk)
        ev(t, "m1", "cosp_ext", None)
    info["used_pairs"] = used_pairs
    return events, info, tl, spk, nk


def _make_cosp(w: dict, gold: dict, r: random.Random, events: list, info: dict, tl, spk, nk) -> None:
    """Co-speakers that link two talks of one day; chosen so that ignoring them can bite."""
    talks = w["talks"]
    base = derive(w, events)
    cands = []
    for a in nk:
        if w["talk_count"][talks[a]["speaker"]] != 1:
            continue
        for b in nk:
            key = frozenset((a, b))
            if a == b or key in info["used_pairs"] or talks[a]["speaker"] == talks[b]["speaker"]:
                continue
            sa, sb = _span(w, gold, a), _span(w, gold, b)
            if sa[0] != sb[0] or _overlap(sa, sb) or talks[a]["track"] == talks[b]["track"]:
                continue
            cands.append((a, b))
    r.shuffle(cands)
    chosen: list[tuple[str, str]] = []
    busy: set[str] = set()
    for a, b in cands:
        if a in busy or b in busy:
            continue
        movable = False
        for t, other in ((a, b), (b, a)):
            so = _span(w, gold, other)
            for pos in _positions(base["dur"][t]):
                sp_t = (pos[0], pos[1], pos[1] + base["dur"][t])
                if _overlap(sp_t, so) and not violations({**gold, t: pos}, base, only=t):
                    movable = True
                    break
            if movable:
                break
        if movable:
            chosen.append((a, b))
            busy |= {a, b}
        if len(chosen) == 6:
            break
    assert len(chosen) >= 3, "not enough co-speaker pairs"
    for i, (a, b) in enumerate(chosen):
        info["used_pairs"].add(frozenset((a, b)))
        person = talks[a]["speaker"]
        if i == len(chosen) - 1:
            _ev(events, tl, spk, b, "B", "cosp", person, CHAIR_EMAIL, "chair", BULLETINS[2])
        else:
            _ev(events, tl, spk, b, r.choice(["m1", "m3"]), "cosp", person)
        info["cosp"].append((a, b))


def _make_qa(w: dict, gold: dict, r: random.Random, events: list, info: dict, tl, spk, nk) -> None:
    """Secretary questions answered by the speaker ("да"/"нет"): the meaning lives in the quoted question.

    Also plants cross-talk traps: a speaker passes on availability of *someone else's* talk.
    """
    talks = w["talks"]
    base = derive(w, events)
    touched_eq = {(e["talk"], e["data"]) for e in events if e["kind"] in ("need", "need_del")}
    has_avail = {e["talk"] for e in events if e["kind"] == "avail"}
    single = [t for t in nk if w["talk_count"][talks[t]["speaker"]] == 1]
    qa_talks = r.sample(nk, 44)
    info["qa"] = {}
    kinds_cycle = ["need_yes", "need_no", "np_no", "np_ok", "avail", "need_yes", "avail_none", "need_no"]
    k = 0
    for t in qa_talks:
        qd = tl[t]["m2"]
        ad = qd + _dt.timedelta(hours=r.randint(2, 20), minutes=r.randint(0, 59))
        items: list[dict] = []
        for _ in range(r.choice([2, 2, 3, 3, 4])):
            kind = kinds_cycle[k % len(kinds_cycle)]
            k += 1
            room = gold[t][2]
            if kind == "need_yes":
                opts = [x for x in sorted(ROOM_EQ[room] - {"STEP", "SIM"})
                        if x not in base["needs"][t] and (t, x) not in touched_eq]
                if not opts:
                    continue
                x = r.choice(opts)
                touched_eq.add((t, x))
                e = _ev(events, tl, spk, t, "qa", "need", x, label="qa", date=ad)
                items.append({"q": "need", "data": x, "yes": True, "ev": e})
            elif kind == "need_no":
                opts = [x for x in ("REC", "WB", "LAN", "SCR2") if x not in base["needs"][t] and (t, x) not in touched_eq]
                if not opts:
                    continue
                x = r.choice(opts)
                touched_eq.add((t, x))
                items.append({"q": "need", "data": x, "yes": False, "ev": None})
            elif kind in ("np_no", "np_ok"):
                cands = [b for b in nk if b != t and frozenset((t, b)) not in info["used_pairs"]
                         and talks[b]["speaker"] != talks[t]["speaker"] and talks[b]["track"] != talks[t]["track"]]
                sa = _span(w, gold, t)
                if kind == "np_no":
                    cands = [b for b in cands if not _overlap(sa, _span(w, gold, b))]
                    near = [b for b in cands if _span(w, gold, b)[0] == sa[0]]
                    cands = near or cands
                b = r.choice(cands)
                info["used_pairs"].add(frozenset((t, b)))
                e = _ev(events, tl, spk, t, "qa", "np", b, label="qa", date=ad) if kind == "np_no" else None
                items.append({"q": "np", "data": b, "yes": kind == "np_ok", "ev": e})
            elif t in single and t not in has_avail and not any(i["q"] == "avail" for i in items):
                has_avail.add(t)
                if kind == "avail":
                    d, st, en = _span(w, gold, t)
                    av = _true_avail(r, d, st, en, r.choice(["only1", "only2", "win1", "mixed"]))
                    e = _ev(events, tl, spk, t, "qa", "avail", av, label="qa", date=ad)
                    items.append({"q": "avail", "data": av, "ev": e})
                else:
                    items.append({"q": "avail", "data": None, "ev": None})
        if items:
            info["qa"][t] = {"qdate": qd, "adate": ad, "items": items}
    # cross-talk traps: the author of one talk passes on availability of another talk
    info["cross"] = {}
    hosts = [t for t in nk if t not in info["qa"]]
    targets = [t for t in single if t not in info["unauth"] and t not in info["cross"]]
    for y in r.sample(targets, 6):
        host = r.choice([h for h in hosts if talks[h]["speaker"] != talks[y]["speaker"]])
        wrong = avail_disjoint(r, {gold[y][0]: FULL})
        slot = r.choice(["m1", "m3"])
        e = _ev(events, tl, spk, y, slot, "avail", wrong, sender=spk[host]["email"], label="cross",
                date=tl[host][slot])
        e["host"] = host
        info["cross"][y] = wrong
    # the secretary files a short summary of the first letter; some summaries are wrong (rules §6: ignore)
    special = set(info["sup"]) | set(info["unauth"]) | set(info["cross"])
    plain_av = [e for e in events if e["kind"] == "avail" and e["label"] == "speaker" and e["slot"] == "m1"
                and e["talk"] not in special and e["talk"] in single]
    info["sec_sum"] = {}
    for i, e in enumerate(r.sample(plain_av, min(12, len(plain_av)))):
        t = e["talk"]
        info["sec_sum"][t] = avail_disjoint(r, e["data"]) if i < 5 else e["data"]
    info["sec_wrong"] = {t: info["sec_sum"][t] for t in list(info["sec_sum"])[:5]}


def _round5(x: float) -> int:
    return int(x // 5 * 5)


