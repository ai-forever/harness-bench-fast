def _chair_reply_body(r: random.Random, w: dict, t: str, rep: dict) -> tuple[str, list]:
    sp = w["people"][w["talks"][t]["speaker"]]
    text = r.choice(CHAIR_OK if rep["ok"] else CHAIR_NO).format(name=f"{sp['first']} {sp['patr']}", data=rep["data"])
    return text + "\n\n" + r.choice(CHAIR_CLOSE), [(text, ("decision", rep))]


def avail_brief(av: dict) -> str:
    parts = []
    for d in sorted(av):
        lo, hi = av[d]
        parts.append(f"{NOMDATE[d]} — " + ("весь день" if (lo, hi) == FULL else f"с {hm(lo)} до {hm(hi)}"))
    return "; ".join(parts) + ("; остальные дни исключены" if len(av) < 3 else "")


def closure_phrase(r: random.Random, day: int, lo: int, hi: int) -> str:
    on = r.choice(ON[day])
    if (lo, hi) == FULL:
        return f"{on} будет закрыт весь день"
    if (lo, hi) == (540, 780):
        return f"{on} будет закрыт до обеда (с 09:00 до 13:00)"
    if (lo, hi) == (840, 1080):
        return f"{on} будет закрыт после обеда (с 14:00 до 18:00)"
    return f"{on} будет закрыт с {hm(lo)} до {hm(hi)}"


