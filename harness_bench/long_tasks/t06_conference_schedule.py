    info["closure_old"] = old
    info["closures"] = closures

    # ---- soft wishes (consistent with the gold) --------------------------
    for t in r.sample(nk, 10):
        d, st, en = _span(w, gold, t)
        ev(t, r.choice(["m1", "m3"]), "soft", (d, *r.choice(_windows_for(st, en))))

    # ---- logistics-only threads -----------------------------------------
    spoken = {e["talk"] for e in events if e["talk"] and e["sender"] == spk[e["talk"]]["email"]}
    for t in r.sample([x for x in nk if x not in spoken], min(11, len([x for x in nk if x not in spoken]))):
        ev(t, "m1", "none", None)


